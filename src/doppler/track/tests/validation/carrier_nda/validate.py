#: The shipped geometry, and the one every table defaults to: 8 samples per
#: symbol with `n = 4`, i.e. a **2-sample** moving-average arm. Both the arm
#: length and `m` move in their own sweeps (§2.4, §2.6, §2.7) because the
#: header's laws are stated across them, not at one point.
SPS = 8
N_ARM = 4
MS = (2, 4, 8)
#: `n` values swept, listed so `arm_len = SPS // n` runs 1, 2, 4, 8. The
#: arm_len = 1 row is the control: no averaging, so no data-transition loss
#: and no overlap between consecutive looks. Several laws in this report are
#: only attributable BECAUSE that row exists.
NS = (8, 4, 2, 1)

BN = 0.01
ZETA = 0.707

#: The standard carrier offset. Small enough to be inside capture at every
#: `bn` swept, so a table about something else is never also a pull-in test.
F0 = 0.001

#: `snr >= 100` is Synth's "clean" sentinel — no AWGN at all. Named rather
#: than written as a literal because a stray 99 silently adds noise to a
#: measurement whose whole point is that nothing else is present.
CLEAN = 100.0

NSYM = 8000

#: The lock EMA's shipped coefficient (`CARRIER_NDA_LOCK_ALPHA`) and the
#: analytic H0 standard deviation the header derives from it:
#: ``sqrt(Var_look * alpha/(2-alpha))`` with ``Var_look = 1/2`` exactly, for
#: every M. `CARRIER_NDA_LOCK_NORM_SD` is that number as a macro; the C test's
#: section 15 pins the macro against the closed form, so this file re-derives
#: it rather than copying the digits.
ALPHA = 0.05
ANALYTIC_SD = sqrt(0.5 * ALPHA / (2.0 - ALPHA))

#: The shipped decision rule, read back off a constructed object where it
#: matters. `CARRIER_NDA_LOCK_DEFAULT_UP` is private to `carrier_nda_core.c`,
#: which is F2: the header's own derivation cited a symbol its reader cannot
#: reach. The Python face cannot read it either, so this report exercises the
#: rule through `configure_lock` instead of asserting the constant.
UP_THRESH = 0.5
N_UP = 64

R = Report()


# ────────────────────────────────────────────────────────── stimulus
def tone(f0: float, nsamp: int, *, snr_db: float = CLEAN, seed: int = 7):
    """An unmodulated carrier at `f0` — the constant-modulus case.

    Generated by `Synth`, which owns the carrier-offset and the noise
    conventions, rather than by an exponential written here. The distinction
    is not cosmetic: this validator's whole §2.6 is a comparison against the
    constant-modulus reference, and a stimulus assembled from a different
    toolchain is a second waveform that has to be kept in agreement with the
    first by hand.
    """
    return np.asarray(
        Synth(
            type="tone",
            freq=f0,
            fs=1.0,
            snr=snr_db,
            snr_mode="fs",
            seed=seed,
        ).steps(nsamp)
    ).astype(np.complex64)


def noise_only(nsamp: int, *, seed: int = 7):
    """Pure noise, no carrier at all — the H0 input.

    The lock statistic is amplitude-invariant by construction (§2.9), so the
    noise LEVEL cannot reach the measurement and is deliberately not stated
    as a parameter: under H0 the limited sample's phase is uniform whatever
    the scale, which is the property §2.7 measures.
    """
    return np.asarray(
        Synth(type="noise", fs=1.0, seed=seed).steps(nsamp)
    ).astype(np.complex64)


def labels(m: int, nsym: int, *, seed: int = 1):
    """Random M-PSK labels from doppler's own PN generator.

    From `PN` — a 15-stage maximal-length sequence, period 32767 — rather
    than from numpy, for the reason the stimulus gate exists: this report
    characterises a C object and its stimulus should come from the C the
    object ships beside.

    Genuinely random consecutive symbols matter more here than the M-fold
    power law suggests. The discriminator is data-INDEPENDENT at lock, which
    is the whole point of an NDA detector, but §2.6 measures what the arm
    loses by averaging ACROSS symbol transitions — and transition density is
    a property of the sequence, so a strongly periodic stimulus would
    understate the loss.
    """
    bits_per = {2: 1, 4: 2, 8: 3}[m]
    raw = np.asarray(
        PN(poly=0, seed=seed, length=15).generate(nsym * bits_per)
    )
    bits = raw[: nsym * bits_per].astype(np.uint8).reshape(nsym, bits_per)
    weights = (1 << np.arange(bits_per)[::-1]).astype(np.uint8)
    return (bits * weights).sum(axis=1).astype(np.uint8)


def psk(
    m: int,
    f0: float,
    nsym: int = NSYM,
    *,
    sps: int = SPS,
    snr_db: float = CLEAN,
    pulse: str = "rect",
    seed: int = 7,
):
    """M-PSK on a carrier at `f0`, with NO symbol-timing alignment.

    The headline stimulus: the loop is handed a modulated stream and given
    no timing information whatsoever, which is the case the M-th power
    exists to make tractable.

    `pulse="rect"` is the default because it is the shape the header's
    arm-window claim is written about — a sample-and-hold symbol stream is
    what "the arm averages across data transitions" describes. `pulse="rrc"`
    is measured once, in §2.1, because it is a materially different regime
    (§2.2 and F12 give what it costs).
    """
    points = mpsk_map(labels(m, nsym, seed=seed + 1), m)
    return np.asarray(
        Synth(
            type="symbols",
            symbols=points,
            sps=sps,
            pulse=pulse,
            rrc_beta=0.35,
            rrc_span=8,
            freq=f0,
            fs=1.0,
            snr=snr_db,
            snr_mode="esno",
            seed=seed,
        ).steps(nsym * sps)
    ).astype(np.complex64)


# ────────────────────────────────────────────────────────── measurement
def loop(m: int, *, n: int = N_ARM, bn: float = BN, sps: int = SPS):
    """A loop at the shipped defaults, seeded at zero — always a cold start."""
    return CarrierNda(bn=bn, zeta=ZETA, init_norm_freq=0.0, sps=sps, n=n, m=m)


def run(x, m: int, *, n: int = N_ARM, bn: float = BN, decim: int = 0):
    """Push one stream through a loop; return it, its output and its probes.

    With `decim`, the four telemetry channels are captured at that rate —
    the object's own instrumentation, rather than anything reconstructed
    from the outputs here. The ring is sized from the record so a long
    sweep cannot silently drop records and report a shorter run.
    """
    c = loop(m, n=n, bn=bn)
    tlm = None
    if decim:
        want = 4 * (len(x) // decim + 1)
        size = 1 << max(12, int(np.ceil(np.log2(max(want, 2)))) + 1)
        tlm = Telemetry(size)
        c.set_telemetry(tlm, "car", decim)
    y = np.asarray(c.steps(x))
    return c, y, (tlm.read_dict() if tlm is not None else {})


def acquired(c, f0: float, *, rel: float = 0.05, floor: float = 1e-5) -> bool:
    """Did this loop end up tracking `f0`, and does it say so?

    Both halves, deliberately. The tracked frequency alone would call a
    SILENT false lock a success — §2.3 shows the loop sitting a whole `1/M`
    away with a lock statistic of +1.0000 — and `locked` alone would call
    the loud dead zone a success on the one run in twenty where the noise
    happens to clear the threshold for the verify count.
    """
    return bool(abs(c.norm_freq - f0) < max(rel * abs(f0), floor) and c.locked)


def capture_edge(
    bn: float, m: int, *, n: int = N_ARM, nsamp: int = 200_000
) -> float:
    """Largest carrier offset this configuration pulls in from cold, bisected.

    Answers a question with a stated budget, because the honest answer
    depends on one: pull-in TIME grows steeply with the offset (§2.5), so a
    "range" measured on a short record is really reporting the record. The
    budget is `nsamp` and it is quoted everywhere this is used.
    """

    def ok(f: float) -> bool:
        c, _, _ = run(tone(f, nsamp), m, n=n, bn=bn)
        return acquired(c, f)

    lo, hi = 1e-4, 0.4
    if not ok(lo):
        return float("nan")
    for _ in range(13):
        mid = 0.5 * (lo + hi)
        lo, hi = (mid, hi) if ok(mid) else (lo, mid)
    return lo


def pullin_samples(
    f0: float,
    bn: float,
    m: int,
    *,
    n: int = N_ARM,
    nsamp: int = 1_000_000,
    decim: int = 64,
    snr_db: float = CLEAN,
    seed: int = 7,
    tol_floor: float = 5e-4,
) -> int:
    """Samples until the tracked frequency reaches and stays within 5% of `f0`.

    Read off the object's own `car.freq` probe, and taken as the LAST
    excursion rather than the first arrival — a loop crossing its target on
    the way past has not settled, and a first-crossing measure reports the
    overshoot as the answer.

    `decim` is the probe's throttle and therefore the answer's RESOLUTION,
    so it is a parameter rather than a constant: §2.10 compares settling
    times that differ by a few percent, and at the default 64 every row of
    that table quantised to the same number and reported a perfect 1.00x
    agreement that was the sampling grid talking.

    `tol_floor` is the absolute part of the settling tolerance and it
    belongs to the NOISE, not to the loop. With noise present a 5%
    relative window at a small offset is tighter than the loop's own
    jitter, so a purely relative test reports a locked loop as never
    having settled -- measured, that alone turned 8/8 acquisitions at
    `u = 0.5` into 4/8 at 6 dB. Noiseless, the floor must be 0: §2.5
    compares offsets of `u * bn / M`, which shrink with M, so a FIXED
    absolute floor is a different relative criterion at each order and
    duly reported M = 8 settling in half the time of M = 2 at the same
    `u`. That was the floor being generous, not the loop being faster.

    Returns `nsamp` when the loop did not end up on `f0` at all, so a
    caller can tell "did not acquire" from "acquired late" by comparing
    against its own budget.
    """
    _, _, rec = run(
        tone(f0, nsamp, snr_db=snr_db, seed=seed), m, n=n, bn=bn, decim=decim
    )
    f = np.asarray(rec.get("car.freq", []))
    if f.size == 0:
        return nsamp
    tol = max(0.05 * abs(f0), tol_floor)
    if abs(f[-1] - f0) >= tol:
        return nsamp
    out = np.flatnonzero(np.abs(f - f0) > tol)
    return (int(out[-1]) + 1) * decim if out.size else 0


def u_max_for(
    t_const: float,
    m: int,
    bn: float,
    *,
    snr_db: float = CLEAN,
    seeds: tuple = (7,),
) -> float:
    """Largest `u = |df|*M/bn` that settles within `t_const` loop constants.

    The inverse of §2.5's law, and the form a composer actually needs: a
    coarse acquisition ahead of this loop has to place the residual inside
    a stated window, and the useful statement of that window is "seed
    within this, and be locked within that many loop time constants".

    Bisected on `u` rather than fitted from the forward sweep, because a
    fit would smooth exactly the knee being located. Every seed in `seeds`
    must clear the budget, so the answer is a worst case over the noise
    realisations rather than a median — a seeding rule that holds half the
    time is not a seeding rule.

    Returns NaN if even the smallest offset misses the budget, which is
    how a too-tight budget reports itself rather than returning a
    meaningless zero.
    """
    budget = int(t_const / bn * 1.5 + 20_000)

    def ok(u: float) -> bool:
        f0 = u * bn / m
        return all(
            pullin_samples(
                f0,
                bn,
                m,
                nsamp=budget,
                decim=8,
                snr_db=snr_db,
                seed=s,
                tol_floor=0.0 if snr_db >= CLEAN else 5e-4,
            )
            * bn
            <= t_const
            for s in seeds
        )

    lo, hi = 0.05, 40.0
    if not ok(lo):
        return float("nan")
    for _ in range(11):
        mid = 0.5 * (lo + hi)
        lo, hi = (mid, hi) if ok(mid) else (lo, mid)
    return lo


def h0_stats(m: int, *, n: int = N_ARM, nsamp: int = 200_000, seed: int = 13):
    """Mean, sd and worst excursion of the lock EMA on noise-only input.

    The first 2000 samples are dropped: the EMA starts at 0 and its own
    transient is not the H0 law. That start is BELOW the H0 mean of zero
    only by chance, so including it biases the sd downward — the direction
    that would flatter the threshold.
    """
    _, _, rec = run(noise_only(nsamp, seed=seed), m, n=n, decim=1)
    v = np.asarray(rec["car.lock"])[2000:]
    return float(v.mean()), float(v.std()), float(v.max())


def false_declares(
    m: int, n: int, n_up: int, *, trials: int = 60, nsamp: int = 200_000
) -> int:
    """Trials, out of `trials`, in which `locked` ever asserts on pure noise.

    The whole trial is one `steps()` call and the verdict is read from the
    `car.locked` probe rather than from the property afterwards: `locked`
    drops again after `n_down` below-threshold samples, so an end-of-run
    poll misses every false lock that has already released — which is most
    of them.
    """
    bad = 0
    for t in range(trials):
        c = loop(m, n=n)
        c.configure_lock(UP_THRESH, 0.4, n_up, 32)
        tlm = Telemetry(1 << 12)
        c.set_telemetry(tlm, "car", 8192)
        c.steps(noise_only(nsamp, seed=7919 * t + 31 * m + n))
        lk = np.asarray(tlm.read_dict().get("car.locked", []))
        bad += int(lk.size > 0 and lk.max() > 0)
    return bad


def residual_carrier(y, m: int) -> float:
    """Frequency left in the de-rotated stream, cycles/sample.

    `steps()` returns the wiped-off samples, so over the settled tail this
    is whatever the loop failed to remove.

    **Measured through the object's own trick, not on the raw phase.** A
    line fitted to `unwrap(angle(y))` measures the DATA on any modulated
    row — the symbol sequence dominates the phase — and duly reported
    8.1e-4 cyc/sample of "residual carrier" on a stream whose tracked
    frequency was correct to 1.2e-7. Limiting the sample and raising it to
    the Mth power is exactly what `carrier_nda_disc` does, and it strips
    the modulation for the same reason: what is left is M times the
    residual carrier phase, so the slope divided by M is the answer. The
    constant-modulus rows are unaffected by the change, which is the check
    that it measures the same quantity.

    Samples whose M-th power lost magnitude are dropped: an RRC stream
    passes through zero between symbols, and the phase of a near-zero
    sample is noise rather than a carrier.
    """
    u = y.astype(np.complex128)
    a = np.abs(u)
    u = np.where(a > 1e-12, u / np.maximum(a, 1e-12), 0.0)
    half = u.size // 2
    z = u[half:] ** m
    keep = np.abs(z) > 0.5
    if keep.sum() < 16:
        return float("nan")
    idx = np.arange(half, u.size)[keep]
    ph = np.unwrap(np.angle(z[keep]))
    return float(np.polyfit(idx, ph, 1)[0] / (2.0 * np.pi * m))


