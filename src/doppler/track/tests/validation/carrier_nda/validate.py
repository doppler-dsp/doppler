            f"external reference, a sync word, or a search bounded to "
            f"`|df| < 1/(2M)` (§2.3).",
            f"**`lock` and `locked` are telemetry, never control.** They "
            f"describe the M-th power, not whether the loop is working: of "
            f"{len(d.esno)} Es/N0 points swept, {tracks} track the carrier "
            f"and only {declares} declare, and an RRC-shaped input at "
            f"M >= 4 tracks to 1e-6 while reading `locked = False`. A "
            f"receiver gated on `locked` will refuse a working loop (§2.2).",
            f"**Pull-in stops at a frequency, not at a multiple of `bn`.** "
            f"The arm window sets an absolute ceiling — {ceiling:.5f} "
            f"cycles/sample at the shipped geometry, M = 4 — which does not "
            f"move with `bn` and is {0.5 / 4 / ceiling:.1f}x tighter than "
            f"the `1/(2M)` aliasing ceiling. Widening the arm tightens it "
            f"further (§2.4).",
            f"**The input level cannot reach the loop.** Eight decades of "
            f"amplitude move the tracked carrier by at most "
            f"{max(max(v) - min(v) for v in d.amp.values()):.1e} "
            f"cycles/sample: the discriminator divides out its own `|z|^M`, "
            f"so there is no AGC in this object and none is wanted (§2.9).",
            f"**What `n` costs is the table in §2.6, not the header's "
            f"closed form.** `1/2 + 1/(M+1)` does not reproduce — measured "
            f"{d.arm_cost[2][NS.index(2)]:.4f} / "
