/**
 * @file RateConverter_core.c
 * @brief Optimal-speed rate conversion cascade -- implementation.
 *
 * Stage selection mirrors _plan_cascade() from the validated Python
 * prototype (src/doppler/resample/rate_converter.py, 33/33 tests).
 *
 * The CIC "compound stage" bundles the CIC decimator and its optional
 * droop-compensating FIR into a single cascade slot so that n_stages
 * exactly equals the number of human-readable stage labels.
 *
 * Intermediate ping-pong buffers (bufs[0] and bufs[1]) are grown lazily
 * on the first execute call.  buf_cap equals n_in so any decimation
 * stage's intermediate output fits without a second alloc.
 */

#include "RateConverter/RateConverter_core.h"

#include "cic/cic_core.h"
#include "fir/fir_core.h"
#include "hbdecim/hbdecim_core.h"
#include "resamp/resamp_core.h"
#include "resample/resample_core.h" /* ciccompmf */
#include "wfm/wfm_dsp.h" /* wfm_rrc_h — the RRC formula's one home */

#include <math.h>
