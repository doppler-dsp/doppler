HEADER = ROOT / header("wfm/wfm_defaults.h")
COMPOSE_H = ROOT / header("wfm/wfm_compose.h")
NAMES_H = ROOT / header("wfm/wfm_names.h")
SURFACE = ROOT / header("wfm/wfm_surface.h")
WFMGEN_C = ROOT / "native" / "src" / "app" / "wfmgen.c"
SCHEMA = ROOT / "docs" / "schema" / "wfmgen.schema.json"
REFERENCE = ROOT / "docs" / "guide" / "wfmgen" / "options.md"

# The C struct each manifest table describes.
STRUCTS = {"source": "wfm_source_t", "segment": "wfm_segment_t"}

BANNER = "wfm_defaults.h — GENERATED by scripts/gen_wfm_defaults.py"


def member(f: dict) -> str:
    """The C struct member a manifest field is: its own name, or -- for a
    field whose bits jm reaches through `c_ptr = "<member>.bits"`, the four
    `wfm_seq_t` sequences -- that member (the manifest's `bits` is the
    struct's `payload`)."""
    ptr = f.get("c_ptr")
    return ptr.split(".", 1)[0] if ptr else f["name"]


def _enums(man: dict) -> dict[str, list[str]]:
    return {e["name"]: list(e["values"]) for e in man.get("enum", [])}


def _literal(field: dict, enums: dict[str, list[str]]) -> str | None:
    """The C initialiser for one field's default, or None to omit it.

    Returns None for a default that is zero in C, because a zero-initialised
    struct already carries it.
    """
    raw = field.get("default")
    if raw is None:
        return None
    name = field["name"]

    # An enum-valued default resolves through the field's OWN declared enum.
    en = field.get("enum")
    if en is not None:
        values = enums.get(en)
        if values is None:
            raise SystemExit(
                f"{name}: enum = {en!r}, which no [[enum]] declares"
            )
        if raw not in values:
            raise SystemExit(
                f"{name}: default {raw!r} is not a member of [[enum]] {en} "
                f"({', '.join(values)})"
            )
        idx = values.index(raw)
        return None if idx == 0 else f"{idx} /* {en}: {raw} */"

    text = str(raw).strip()
    ctype = field.get("type", "")
    if ctype in ("double", "float"):
        return None if float(text) == 0.0 else text
    # Everything else is an integer-ish scalar. A non-numeric default here is
    # a string type (a path, a name); those have no place in a struct literal.
    try:
        n = int(text, 0)
    except ValueError:
        return None
    return None if n == 0 else str(n)


_DECL = re.compile(r"^([ \t]*)[A-Za-z_][\w \t\*]*?\b(\w+)(?:\[\w*\])?;", re.M)


def member_docs(text: str, struct: str) -> dict[str, dict]:
    """Each member's doc comment in `typedef struct { ... } <struct>;`.

    **A member's doc is its trailing comment** -- the `/* ... */` that opens
    on the declaration's own line -- **or, when it has none, the block
    comment directly above it** (only whitespace between the two). A block
    comment above a member that ALSO has a trailing comment is a design note
    and is not its doc.

    Returns ``{name: {"doc", "start", "end", "col", "form"}}`` where the doc
    is the comment's words joined by single spaces, ``start``/``end`` span
    the whole comment in `text`, ``col`` is the column the ``/*`` opens at,
    and ``form`` is ``"trailing"`` or ``"above"``. A member with neither has
    no entry.
    """
    end = text.index(f"}} {struct};")
    begin = text.rindex("typedef struct {", 0, end)
    # A comment line can read like a declaration ("... other types;"), so
    # every match inside a comment is skipped rather than trusted.
    comments = [
        (c.start(), c.end())
        for c in re.finditer(r"/\*.*?\*/", text[:end], re.S)
        if c.end() > begin
    ]
    out: dict[str, dict] = {}
    for m in _DECL.finditer(text, begin, end):
        if any(a <= m.start() < b for a, b in comments):
            continue
        name = m.group(2)
        line_end = text.index("\n", m.end())
        rest = text[m.end() : line_end]
        if "/*" in rest:
            start = m.end() + rest.index("/*")
            form = "trailing"
        else:
            above = text[begin : m.start()].rstrip()
            if not above.endswith("*/"):
                continue
            start = text.rindex("/*", begin, m.start())
            line_start = text.rindex("\n", 0, start) + 1
            if text[line_start:start].strip():
                continue  # the previous member's trailing comment
            form = "above"
        close = text.index("*/", start) + 2
        doc = " ".join(text[start + 2 : close - 2].split())
        col = start - (text.rindex("\n", 0, start) + 1)
        out[name] = {
            "doc": doc,
            "start": start,
            "end": close,
            "col": col,
            "form": form,
        }
    return out


def doc_drift(man: dict, header_text: str) -> list[str]:
    """Fields whose manifest `doc` differs from the header's comment.

    The header is the field's one text (docs/design/wfmgen.md, "One surface
    table"); the manifest `doc` exists only because jm still reads it for
    the Python docstring (just-makeit#1703), so it must be the same words.
    """
    bad = []
    mc = man["module"]["wfm_compose"]
    for kind, struct in STRUCTS.items():
        docs = member_docs(header_text, struct)
        for f in mc[kind].get("fields", []):
            have = " ".join(str(f.get("doc", "")).split())
            want = docs.get(member(f), {}).get("doc", "")
            if have != want:
                bad.append(
                    f"{kind}.{f['name']}: manifest doc != header comment\n"
                    f"    manifest: {have or '(none)'}\n"
                    f"    header:   {want or '(none)'}"
                )
    return bad


def render() -> str:
    man = tomllib.loads(MANIFEST.read_text(encoding="utf-8"))
    enums = _enums(man)
    mc = man["module"]["wfm_compose"]

    out: list[str] = [
        "/*",
        f" * {BANNER}",
        " *",
        " * Do not edit. `just-makeit.toml` is the one declaration of a",
        " * default; this is that declaration rendered for C, so the CLI, a",
        " * C caller and Python cannot disagree about one (doppler#1142).",
        " *",
        " * Only NON-ZERO defaults appear: a zero is what a zero-initialised",
        " * struct already gives, and spelling it would say nothing.",
        " *",
        " * An enum-valued default is rendered as the index of its name in",
        " * the field's OWN declared [[enum]], with the name in a comment, so",
        " * reordering that enum moves this file rather than silently",
        " * changing what the value means.",
        " */",
        "#ifndef WFM_DEFAULTS_H",
        "#define WFM_DEFAULTS_H",
        "",
    ]

    for kind, macro in (
        ("source", "WFM_SOURCE_DEFAULTS"),
        ("segment", "WFM_SEGMENT_DEFAULTS"),
    ):
        rows = []
        for f in mc[kind].get("fields", []):
            lit = _literal(f, enums)
            if lit is not None:
                rows.append((f["name"], lit))
        out.append(f"/* Non-zero defaults for a wfm_{kind}_t. */")
        out.append(f"#define {macro} \\")
        body = ", \\\n".join(f"    .{n} = {v}" for n, v in rows)
        out.append("  { \\")
        out.append(body + " \\")
        out.append("  }")
        out.append("")

    out.append("#endif /* WFM_DEFAULTS_H */")
    return "\n".join(out) + "\n"


# A field's C type, as the kind of value the surface reads into it.
_KINDS = {
    "double": "WFM_SV_DOUBLE",
    "int": "WFM_SV_INT",
    "size_t": "WFM_SV_SIZE",
    "uint32_t": "WFM_SV_U32",
    "uint64_t": "WFM_SV_U64",
    "float _Complex*": "WFM_SV_SYMBOLS",
}

SURFACE_BANNER = "wfm_surface.h — GENERATED by scripts/gen_wfm_defaults.py"


def surface_rows(man: dict) -> list[dict]:
    """The surface table: one row per field that declares `cli` or `json`.

    Everything but the spelling is DERIVED from what the manifest and the
    headers already say -- the value kind from the field's C type, the
    choice table from its `enum` (through `wfm_names.h`'s `SSOT: enum=`
    markers, read by the same parser that gates them), the upper bound and
    the range bit from the table's `ranged` list. The new keys are only
    what nothing else states: the spellings (`cli`, `json`), the help
    placement, and the JSON policy (`json_omit`, `json_when`,
    `json_required`, `json_type`).
    """
    mc = man["module"]["wfm_compose"]
    parsed = [
        t for t in _tables(NAMES_H.read_text(encoding="utf-8")) if t.enum
    ]
    tables = {t.enum: t.name for t in parsed}
    values_of = {t.enum: t.values for t in parsed}
    rows = []
    for kind in STRUCTS:
        ranged = {r["name"]: r["flag"] for r in mc[kind].get("ranged", [])}
        for f in mc[kind].get("fields", []):
            if "cli" not in f and "json" not in f:
                continue
            name = f["name"]
            en = f.get("enum")
            if en is not None:
                if en not in tables:
                    raise SystemExit(
                        f"{kind}.{name}: enum = {en!r} has no table in "
                        f"{NAMES_H.relative_to(ROOT)}"
                    )
                vkind, choices = "WFM_SV_CHOICE", tables[en]
            elif f.get("c_ptr"):
                # A `wfm_seq_t` reached through `<member>.bits`: a Field.
                vkind, choices = "WFM_SV_FIELD", None
            else:
                ctype = f.get("type", "")
                if ctype not in _KINDS:
                    raise SystemExit(
                        f"{kind}.{name}: type {ctype!r} has no surface kind"
                    )
                vkind, choices = _KINDS[ctype], None
            # The CLI stores a range bit in `src.ranged` for a double and in
            # `seg.ranged` for a size_t (OPT_RANGE_D / OPT_RANGE_N), so any
            # other pairing would set the wrong struct's bitmask silently.
            if name in ranged and (kind, vkind) not in (
                ("source", "WFM_SV_DOUBLE"),
                ("segment", "WFM_SV_SIZE"),
            ):
                raise SystemExit(
                    f"{kind}.{name}: a ranged {vkind} {kind} field has no "
                    "CLI range kind; wfmgen ranges source doubles and "
                    "segment sizes only"
                )
            rows.append(
                {
                    "owner": kind,
                    "name": name,
                    "member": member(f),
                    "field_reps": f.get("field_reps"),
                    "cli": f.get("cli"),
                    "json": f.get("json"),
                    "json_required": bool(f.get("json_required")),
                    "json_omit": f.get("json_omit"),
                    "json_bool": f.get("json_type") == "bool",
                    "json_when": f.get("json_when"),
                    "json_schema": dict(f.get("json_schema", {})),
                    "json_range": f.get("json_range"),
                    "kind": vkind,
                    "choices": choices,
                    "range_bit": ranged.get(name),
                    "unit_interval": bool(f.get("unit_interval")),
                    "metavar": f.get("metavar"),
                    "section": f.get("help_section"),
                    "default": f.get("default"),
                    "values": values_of.get(en) if en else None,
                }
            )
    _resolve_when(rows)
    return rows


def _resolve_when(rows: list[dict]) -> None:
    """Turn each `json_when = { <field> = "<choice>" }` into a row index and
    a choice index, refusing a condition the table cannot evaluate."""
    by = {(r["owner"], r["name"]): r for r in rows}
    for r in rows:
        w = r["json_when"]
        if not w:
            continue
        if r["json_omit"] not in (None, "default"):
            raise SystemExit(f'{r["name"]}: json_omit must be "default"')
        if len(w) != 1:
            raise SystemExit(f"{r['name']}: json_when names ONE field")
        ((field, value),) = w.items()
        cond = by.get((r["owner"], field))
        if cond is None or not cond["values"]:
            raise SystemExit(
                f"{r['owner']}.{r['name']}: json_when names {field!r}, "
                "which is not a choice row of the same struct"
            )
        if value not in cond["values"]:
            raise SystemExit(
                f"{r['owner']}.{r['name']}: json_when {field} = {value!r} "
                f"is not one of {', '.join(cond['values'])}"
            )
        r["when_row"] = f"WFM_SURFACE_{r['owner']}_{field}"
        r["when_value"] = cond["values"].index(value)


# The column a flag's description starts at, and the line width. A flag
# and metavar that reach the column put the description on the next line.
HELP_COL = 18
HELP_WIDTH = 79

_SENTENCE = re.compile(r"^(.*?[.])(?:\s|$)", re.S)


def first_sentence(doc: str) -> str:
    """A field's help line: the first sentence of its header comment."""
    m = _SENTENCE.match(doc)
    return m.group(1) if m else doc


def help_lines(row: dict, doc: str) -> list[str]:
    """One option's --help lines: flag, metavar, description, wrapped.

    The description is the header comment's first sentence, then the
    choices and the default from the table -- never restated by hand, so
    they cannot disagree with what the parser accepts.
    """
    mv = row["metavar"]
    if row["range_bit"]:
        mv = f"{mv}[:{mv}]"
    head = f"  {row['cli']} {mv}"
    text = first_sentence(doc)
    if row["values"]:
        text += " One of: " + " | ".join(row["values"]) + "."
    if row["default"] is not None:
        # A no-break space: the wrap may not split "(default" from its
        # value, and textwrap does not count U+00A0 as a place to break.
        text += f" (default\u00a0{row['default']})"
    words = textwrap.wrap(
        text,
        width=HELP_WIDTH - HELP_COL,
        break_on_hyphens=False,
        break_long_words=False,
    )
    pad = " " * HELP_COL
    if len(head) < HELP_COL:
        out = [head.ljust(HELP_COL) + words[0]]
    else:
        out = [head, pad + words[0]]
    out += [pad + w for w in words[1:]]
    return [x.replace("\u00a0", " ") for x in out]


def _c_string(line: str) -> str:
    esc = line.replace("\\", "\\\\").replace('"', '\\"')
    return f'  "{esc}\\n"'


def render_help(rows: list[dict]) -> list[str]:
    """`#define WFM_SURFACE_HELP_<SECTION>`, one string per help section.

    wfmgen's USAGE[] keeps its section headings and prose and splices these
    in where the option lines go, so an option's help is generated from
    the same row the parser reads.
    """
    docs = {
        kind: member_docs(COMPOSE_H.read_text(encoding="utf-8"), struct)
        for kind, struct in STRUCTS.items()
    }
    sections: dict[str, list[str]] = {}
    # Segment rows first: --fs and --count lead the signal section.
    cli_rows = [r for r in rows if r["cli"]]
    for r in sorted(cli_rows, key=lambda r: r["owner"] != "segment"):
        if not r["section"] or not r["metavar"]:
            raise SystemExit(
                f"{r['owner']}.{r['name']}: a `cli` row needs `metavar` and "
                "`help_section`"
            )
        doc = docs[r["owner"]].get(r["member"], {}).get("doc")
        if not doc:
            raise SystemExit(
                f"{r['owner']}.{r['name']}: no header comment to take its "
                f"help from, in {COMPOSE_H.relative_to(ROOT)}"
            )
        sections.setdefault(r["section"], []).extend(help_lines(r, doc))
    out = ["/* --help option lines, one string per USAGE section. */"]
    for sec, lines in sections.items():
        out.append(f"#define WFM_SURFACE_HELP_{sec} \\")
        out += [_c_string(x) + " \\" for x in lines[:-1]]
        out.append(_c_string(lines[-1]))
        out.append("")
    return out


def help_splice_errors(man: dict) -> list[str]:
    """Where wfmgen's USAGE[] and the generated help lines disagree.

    Two failures, and the compiler sees neither: a section macro USAGE never
    splices in (its options vanish from --help), and a HAND-WRITTEN line for
    a flag the table owns (a second, drifting copy of its help -- the thing
    generating the lines exists to end).
    """
    src = WFMGEN_C.read_text(encoding="utf-8")
    a = src.index("static const char USAGE[]")
    usage = src[a : src.index(";\n", a)]
    rows = [r for r in surface_rows(man) if r["cli"]]
    bad = []
    for sec in sorted({r["section"] for r in rows if r["section"]}):
        if f"WFM_SURFACE_HELP_{sec}" not in usage:
            bad.append(
                f"USAGE[] never splices WFM_SURFACE_HELP_{sec}, so its "
                "options are missing from --help"
            )
    hand = "".join(re.findall(r'"((?:[^"\\]|\\.)*)"', usage))
    for line in hand.split("\\n"):
        # An OPTION line, not prose that opens with a flag ("--count is
        # honoured verbatim"): two spaces, the flag, an optional UPPERCASE
        # metavar, then a two-space gap or the end of the line.
        m = re.match(
            r"  (--[A-Za-z0-9-]+)(?: [A-Z][A-Z0-9_:\[\]-]*)?(?: {2,}|$)", line
        )
        if m and m.group(1) in {r["cli"] for r in rows}:
            bad.append(
                f"USAGE[] has a hand-written line for {m.group(1)}, which "
                "the surface table generates: delete it"
            )
    return bad


def _typed_default(r: dict):
    """A row's manifest default as the JSON value a scene would carry."""
    raw = r["default"]
    if raw is None:
        return None
    if r["kind"] == "WFM_SV_CHOICE":
        return raw
    if r["json_bool"]:
        return int(raw, 0) != 0
    if r["kind"] == "WFM_SV_DOUBLE":
        return float(raw)
    return int(raw, 0)


def row_schema(r: dict, doc: str) -> dict:
    """One row's JSON Schema property, from the row alone.

    The type from the C type (unsigned -> `minimum: 0`), the enum from the
    choice table, `(0, 1]` from `unit_interval`, a range as `oneOf` scalar
    or a [lo, hi] pair, then the row's own `json_schema` constraints. The
    description is the header comment, plus what only the JSON face adds.
    """
    if r["kind"] == "WFM_SV_CHOICE":
        scalar: dict = {"type": "string", "enum": list(r["values"])}
    elif r["kind"] == "WFM_SV_FIELD":
        # The Field grammar (frame-description.md F.1); dp_wfm_field_parse
        # is its one reader, so the schema checks only that it is text.
        scalar = {"type": "string", "minLength": 1}
    elif r["json_bool"]:
        scalar = {"type": "boolean"}
    elif r["kind"] == "WFM_SV_DOUBLE":
        scalar = {"type": "number"}
    elif r["kind"] in ("WFM_SV_SIZE", "WFM_SV_U32", "WFM_SV_U64"):
        scalar = {"type": "integer", "minimum": 0}
    else:
        scalar = {"type": "integer"}
    if r["unit_interval"]:
        scalar.update({"exclusiveMinimum": 0, "maximum": 1})
    scalar.update(r["json_schema"])
    if r["range_bit"]:
        rng = r["json_range"] or (
            "number_range" if r["kind"] == "WFM_SV_DOUBLE" else "count_range"
        )
        prop: dict = {"oneOf": [scalar, {"$ref": f"#/$defs/{rng}"}]}
        doc += " Scalar, or a [lo, hi] pair drawn uniformly per repeat."
    else:
        prop = scalar
    if r["json_omit"]:
        doc += " Omitted from a record at its default."
    d = _typed_default(r)
    if d is not None:
        prop["default"] = d
    prop["description"] = doc
    return prop


def render_schema() -> str:
    """docs/schema/wfmgen.schema.json with every table row's property
    generated, and every other key -- the frame, the payload, the codes --
    left exactly as its owner wrote it.

    A source row is defined once, under `source`; `inline_segment` refers
    to it. A segment row is defined under `inline_segment`; `sum_segment`
    refers to it. Nothing else in the file is touched.
    """
    man = tomllib.loads(MANIFEST.read_text(encoding="utf-8"))
    schema = json.loads(SCHEMA.read_text(encoding="utf-8"))
    defs = schema["$defs"]
    text = COMPOSE_H.read_text(encoding="utf-8")
    docs = {k: member_docs(text, st) for k, st in STRUCTS.items()}
    for r in surface_rows(man):
        if not r["json"]:
            continue
        key, doc = r["json"], docs[r["owner"]][r["member"]]["doc"]
        if r["owner"] == "source":
            defs["source"]["properties"][key] = row_schema(r, doc)
            defs["inline_segment"]["properties"][key] = {
                "$ref": f"#/$defs/source/properties/{key}"
            }
        else:
            defs["inline_segment"]["properties"][key] = row_schema(r, doc)
            defs["sum_segment"]["properties"][key] = {
                "$ref": f"#/$defs/inline_segment/properties/{key}"
            }
    # A $defs entry only the table rows referred to is gone with them.
    body = json.dumps(schema)
    for name in list(defs):
        if f'"#/$defs/{name}"' not in body.replace(
            json.dumps({name: defs[name]})[1:-1], ""
        ):
            del defs[name]
            body = json.dumps(schema)
    return json.dumps(schema, indent=2, ensure_ascii=False) + "\n"


def _md(text: str) -> str:
    return text.replace("|", "\\|")


def render_reference() -> str:
    """docs/guide/wfmgen/options.md: every table field on every face.

    One row per field, so the flag, the scene key, the Python keyword, the
    type, the default and the meaning are read off one line rather than
    matched up across three pages -- and none of it is typed twice.
    """
    man = tomllib.loads(MANIFEST.read_text(encoding="utf-8"))
    text = COMPOSE_H.read_text(encoding="utf-8")
    docs = {k: member_docs(text, st) for k, st in STRUCTS.items()}
    out = [
        "# Field reference",
        "",
        "<!-- GENERATED by scripts/gen_wfm_defaults.py from just-makeit.toml",
        "     and wfm/wfm_compose.h. Do not edit: change the field's header",
        "     comment or its manifest row, then run",
        "     `python scripts/gen_wfm_defaults.py --write`. -->",
        "",
        "Every field of a wfmgen source or segment, on each face that",
        "exposes it: the `wfmgen` flag, the scene-file key, and the Python",
        "keyword. The description is the field's header comment, the same",
        "text as `wfmgen --help` (its first sentence) and the Python",
        "docstring. A ranged field also takes a `LO:HI` range on the command",
        "line, or a `[lo, hi]` pair in a scene, drawn uniformly per repeat.",
        "",
        "On the command line an integer is decimal or `0x` hex, and a",
        "leading `0` is decimal, never octal. Every number must be the",
        "whole value: `4x`, `0.1abc` and an empty value are refused, naming",
        "the flag. A sample count (`--count`, `--off`, `--delay`, each",
        "side of a range) is a whole, non-negative number: `1e3` is 1000,",
        "and `1.5` or `-1` is refused.",
        "",
        "Framing, payload and coding keys are described in",
        "[Waveforms](waveforms.md) and [Scenes](scenes.md).",
    ]
    titles = {"source": "Source fields", "segment": "Segment fields"}
    rows = surface_rows(man)
    for owner in ("segment", "source"):
        out += [
            "",
            f"## {titles[owner]}",
            "",
            "| Python | CLI | JSON | Type | Default | Description |",
            "| --- | --- | --- | --- | --- | --- |",
        ]
        for r in (r for r in rows if r["owner"] == owner):
            if r["kind"] == "WFM_SV_CHOICE":
                typ = "one of " + ", ".join(f"`{v}`" for v in r["values"])
            elif r["json_bool"]:
                typ = "bool"
            elif r["kind"] == "WFM_SV_DOUBLE":
                typ = "number"
            elif r["kind"] == "WFM_SV_SYMBOLS":
                typ = "complex stream"
            elif r["kind"] == "WFM_SV_FIELD":
                typ = (
                    "[Field](../../design/frame-description.md#f1-the-grammar)"
                )
            else:
                typ = "integer"
            if r["range_bit"]:
                typ += ", or a range"
            cli = f"`{r['cli']} {r['metavar']}`" if r["cli"] else "—"
            js = f"`{r['json']}`" if r["json"] else "—"
            dflt = f"`{r['default']}`" if r["default"] is not None else "—"
            doc = docs[owner][r["member"]]["doc"]
            out.append(
                f"| `{r['name']}` | {cli} | {js} | {_md(typ)} | {dflt} | "
                f"{_md(doc)} |"
            )
    return "\n".join(out) + "\n"


def render_surface() -> str:
    man = tomllib.loads(MANIFEST.read_text(encoding="utf-8"))
    rows = surface_rows(man)
    owner_c = {"source": "WFM_SURF_SOURCE", "segment": "WFM_SURF_SEGMENT"}
    out = [
        "/*",
        f" * {SURFACE_BANNER}",
        " *",
        " * Do not edit. One row per wfm source or segment field that a",
        " * face other than Python exposes, generated from `just-makeit.toml`",
        " * (the rows that declare `cli`) and the headers it names. Every",
        " * face that reads a field by name reads it from here, so a field",
        " * cannot be spelled, typed or bounded two ways",
        ' * (docs/design/wfmgen.md, "One surface table"; doppler#853).',
        " */",
        "#ifndef WFM_SURFACE_H",
        "#define WFM_SURFACE_H",
        "",
        "#include <stddef.h>",
        "",
        '#include "doppler/wfm/wfm_compose.h"',
        '#include "doppler/wfm/wfm_names.h"',
        "",
        "/* Which struct a row's offsets are into. */",
        "typedef enum",
        "{",
        "  WFM_SURF_SOURCE,  /* wfm_source_t */",
        "  WFM_SURF_SEGMENT, /* wfm_segment_t */",
        "} wfm_surf_owner_t;",
        "",
        "/* What kind of value a row holds. */",
        "typedef enum",
        "{",
        "  WFM_SV_DOUBLE,",
        "  WFM_SV_INT,",
        "  WFM_SV_SIZE,",
        "  WFM_SV_U32,",
        "  WFM_SV_U64,",
        "  WFM_SV_CHOICE,  /* an int index into `choices` */",
        "  WFM_SV_SYMBOLS, /* float _Complex *, its count at `len_off` */",
        "  WFM_SV_FIELD,   /* a wfm_seq_t, as a Field (wfm_frame.h) */",
        "} wfm_sv_kind_t;",
        "",
        "typedef struct",
        "{",
        "  const char        *name;  /* the struct member */",
        "  const char        *cli;   /* the flag; NULL = not on the CLI */",
        "  wfm_surf_owner_t   owner;",
        "  wfm_sv_kind_t      kind;",
        "  size_t             off;       /* offsetof the member */",
        "  unsigned           range_bit; /* WFM_RANGE_*; 0 = not ranged */",
        "  size_t             hi_off;    /* `<name>_hi`, if ranged */",
        "  size_t             len_off;   /* WFM_SV_SYMBOLS: the count */",
        "  size_t             reps_off;  /* WFM_SV_FIELD: where *REPS goes;",
        "                                    0 = the field does not repeat */",
        "  const char *const *choices;   /* WFM_SV_CHOICE: the names */",
        "  int                n_choices;",
        "  int                unit_interval; /* require 0 < v <= 1 */",
        "  const char        *json;          /* the scene/record key */",
        "  int                json_required; /* absent/unknown: refuse */",
        "  int                json_omit;     /* not written at its default */",
        "  int                json_bool;     /* written as true/false */",
        "  int                has_when;      /* written only when ... */",
        "  int                when_row;      /* ... this row's choice ... */",
        "  int                when_value;    /* ... is this index */",
        "} wfm_surface_row_t;",
        "",
        "/* A row's index: WFM_SURFACE_<owner>_<name>. */",
        "enum",
        "{",
    ]
    for r in rows:
        out.append(f"  WFM_SURFACE_{r['owner']}_{r['name']},")
    out += ["  WFM_SURFACE_N", "};", ""]
    out.append("static const wfm_surface_row_t WFM_SURFACE[WFM_SURFACE_N] = {")
    for r in rows:
        struct = STRUCTS[r["owner"]]
        n = r["name"]
        fields = [f'.name = "{n}"']
        if r["cli"]:
            fields.append(f'.cli = "{r["cli"]}"')
        fields += [
            f".owner = {owner_c[r['owner']]}",
            f".kind = {r['kind']}",
            f".off = offsetof ({struct}, {r['member']})",
        ]
        if r["range_bit"]:
            fields += [
                f".range_bit = {r['range_bit']}",
                f".hi_off = offsetof ({struct}, {n}_hi)",
            ]
        if r["kind"] == "WFM_SV_SYMBOLS":
            fields.append(f".len_off = offsetof ({struct}, n_{n})")
        if r["field_reps"]:
            fields.append(
                f".reps_off = offsetof ({struct}, {r['field_reps']})"
            )
        if r["choices"]:
            c = r["choices"]
            fields += [
                f".choices = {c}",
                f".n_choices = (int)(sizeof {c} / sizeof *{c})",
            ]
        if r["unit_interval"]:
            fields.append(".unit_interval = 1")
        if r["json"]:
            fields.append(f'.json = "{r["json"]}"')
        if r["json_required"]:
            fields.append(".json_required = 1")
        if r["json_omit"] == "default":
            fields.append(".json_omit = 1")
        if r["json_bool"]:
            fields.append(".json_bool = 1")
        if r.get("when_row"):
            fields += [
                ".has_when = 1",
                f".when_row = {r['when_row']}",
                f".when_value = {r['when_value']}",
            ]
        out.append(f"  [WFM_SURFACE_{r['owner']}_{n}] = {{")
        out += [f"    {x}," for x in fields]
        out.append("  },")
    out += ["};", ""]
    out += render_help(rows)
    out.append("#endif /* WFM_SURFACE_H */")
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    args = ap.parse_args()

    drift = doc_drift(
        tomllib.loads(MANIFEST.read_text(encoding="utf-8")),
        COMPOSE_H.read_text(encoding="utf-8"),
    )
    if drift:
        # Not fixable by --write: which of the two texts is right is a
        # judgement, and the header is the one to edit (then copy it).
        print(
            "gen_wfm_defaults: a field's manifest `doc` differs from its "
            f"comment in {COMPOSE_H.relative_to(ROOT)}. The header is the "
            "one text; make the manifest doc match it.",
            file=sys.stderr,
        )
        for d in drift:
            print("  " + d, file=sys.stderr)
        return 1

    splice = help_splice_errors(
        tomllib.loads(MANIFEST.read_text(encoding="utf-8"))
    )
    if splice:
        for d in splice:
            print(f"gen_wfm_defaults: {d}", file=sys.stderr)
        return 1

    outputs = (
        (HEADER, render()),
        (SURFACE, render_surface()),
        (SCHEMA, render_schema()),
        (REFERENCE, render_reference()),
    )
    if args.write:
        for path, fresh in outputs:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(fresh, encoding="utf-8")
            print(f"gen_wfm_defaults: wrote {path.relative_to(ROOT)}")
        return 0

    bad = 0
    for path, fresh in outputs:
        rel = path.relative_to(ROOT)
        if not path.is_file():
            print(
                f"gen_wfm_defaults: {rel} is MISSING — run `python "
                "scripts/gen_wfm_defaults.py --write`",
                file=sys.stderr,
            )
            bad = 1
        elif path.read_text(encoding="utf-8") != fresh:
            print(
                f"gen_wfm_defaults: {rel} is STALE — the manifest has moved "
                "since it was generated. Run `python "
                "scripts/gen_wfm_defaults.py --write`.",
                file=sys.stderr,
            )
            bad = 1
    if bad:
        return 1
    print(
        "gen_wfm_defaults: OK — the C defaults and the surface table match "
        "the manifest, and every field's doc matches its header comment"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
