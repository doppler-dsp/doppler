def build(write: bool = True) -> Report:
    """Measure, review and assert; emit the report only when asked.

    ``write=False`` is the pytest path: every measurement still runs, so
    every limit is genuinely exercised, but nothing is written into the
    repo. See ``doppler/tests/_validation_common.py``.
    """
    global R
    R = Report(write=write)
    if write:
        DATA.mkdir(parents=True, exist_ok=True)
    section_summary()
    d = characterise()
    review(d)
    limits(d)
    executive(d)
    if write:
        plots(d)
    R.summary(
        "\n- Raw sweeps: `data/esno.csv`, `data/capture_map.csv`, "
        "`data/pullin_edge.csv`, `data/pullin_time.csv`, `data/seeding.csv`, "
        "`data/arm_cost.csv`, `data/lock_h0.csv`, `data/verify_count.csv` — "
        "so any number above can be re-derived rather than taken on the "
        "report's word."
    )
    R.emit(HERE / "results.md")
    return R


if __name__ == "__main__":
    sys.exit(cli(build, HERE))
