# ═════════════════════════════════════════════════ 4. LIMITS
def limits(d: Data) -> None:
    print("\nPHASE 3 — LIMITS")
    R.md("## 4. Limits — the certified envelope")
    R.md()
    R.md(
        "Claims a caller may rely on. A failure here is a regression, not a "
        "new finding."
    )
    R.md()

    # --- the S-curve, and the parity argument that rests on it ---------
    R.limit(
        len(d.zeros) == 2,
        f"the TED S-curve has exactly two zeros per symbol "
        f"({len(d.zeros)} measured)",
    )
    R.limit(
        len(d.zeros) == 2 and (d.zeros[0][1] > 0) != (d.zeros[1][1] > 0),
        "the two zeros have OPPOSITE slope — one stable, one unstable, "
        "which is why the strobe parity resolves itself",
    )
    R.limit(
        len(d.zeros) == 2
        and abs(abs(d.zeros[0][0] - d.zeros[1][0]) - 0.5) < 0.06,
        "the unstable zero sits half a symbol from the stable one",
    )
    R.limit(
        0.8 < d.slope_meas < 1.3,
        f"the normalised S-curve slope at lock is unity to within 30% "
        f"({d.slope_meas:.4f}) — the construct-time ted_scale is correct, "
        f"and as of F15's resolution this now holds for dttl as well",
    )
    _gb = [abs(v) for _, v, _s in d.beta_slope["gardner"]]
    _db = [abs(v) for _, v, _s in d.beta_slope["dttl"]]
    # The spread claim has to clear its own noise, or it is a statement
    # about the seed rather than about the object. Endpoints, in units of
    # their own seed-to-seed sd.
    R.limit(
        max(_gb) / min(_gb) < 1.2,
        f"gardner's normalised slope holds unity across the whole roll-off "
        f"range ({min(_gb):.2f} to {max(_gb):.2f}) — `bn` names one "
        f"bandwidth at every beta, which is the header's claim",
    )
    # Was a RATCHET on an 8.7x spread while F15 was open. F15 was the
    # measurement differentiating the T/2 equilibrium, so there is no
    # breakage left to ratchet and this is now the same real gate Gardner
    # gets. A ratchet may only shrink; this one shrank to nothing.
    R.limit(
        max(_db) / min(_db) < 1.2,
        f"dttl's normalised slope holds unity too ({min(_db):.2f} to "
        f"{max(_db):.2f}) — the 8.7x that stood here was F15, and it was "
        f"the wrong zero rather than the wrong detector",
    )
    R.limit(
        all(
            v["eyes"][v["stable_i"]]
            > 1.15
            * max(e for i, e in enumerate(v["eyes"]) if i != v["stable_i"])
            for v in d.scurve_by_ted.values()
            if len(v["eyes"]) == 2
        ),
        "the zero this report calls stable carries a decisively wider eye "
        "than the other — the discrimination that replaced a hard-coded "
        "slope-sign test, and the one that does not depend on which way "
        "the tau axis runs (F15)",
    )
    R.limit(
        all(len(v["zeros"]) == 2 for v in d.scurve_by_ted.values()),
        "BOTH detectors carry exactly two zeros per symbol, so the parity "
        "argument covers the whole ted axis and not just the default",
    )
    R.limit(
        all(
            len(v["zeros"]) == 2
            and (v["zeros"][0][1] > 0) != (v["zeros"][1][1] > 0)
            for v in d.scurve_by_ted.values()
        ),
        "and on both, the two zeros have opposite slope",
    )

    # --- the amplitude law, per detector -------------------------------
    R.limit(
        abs(d.amp_law["gardner"] - 2.0) < 0.05,
        f"gardner's raw error scales as A^2 "
        f"(fitted {d.amp_law['gardner']:.3f}) — a 2x level error is 4x the "
        f"designed loop gain",
    )
    R.limit(
        abs(d.amp_law["dttl"] - 1.0) < 0.05,
        f"dttl's raw error scales as A^1 (fitted {d.amp_law['dttl']:.3f}), "
        f"not A^2 — the two detectors do NOT share a level-error budget",
    )
    R.limit(
        d.amp_law["gardner"] - d.amp_law["dttl"] > 0.9,
        "and the two exponents differ by ~1, which is the reason no single "
        "normaliser applied outside the detectors could serve both",
    )

    # --- dttl is a supported detector, not just a declared one ---------
    _dj = d.resid_by_ted["dttl"] / d.scurve_by_ted["dttl"]["slope"]
    _gj = d.resid_by_ted["gardner"] / d.scurve_by_ted["gardner"]["slope"]
    R.limit(
        _dj < _gj,
        f"dttl rests closer to the eye centre than gardner "
        f"({_dj:.4f} vs {_gj:.4f} symbols) — the header's 'lower self-noise "
        f"near lock', measured",
    )
    R.limit(
        all(
            max(vals) < -30.0
            for bn, vals in d.bn_rows_by_ted["dttl"]
            if bn >= 0.005
        ),
        "dttl demodulates below -30 dB EVM on every planned cascade at "
        "every recommended bn — the detector works, on all three plans",
    )

    # --- acquisition ---------------------------------------------------
    R.limit(
        all(t[1] >= 0 for t in d.lock_time),
        "every initial timing offset across a whole symbol acquires lock",
    )
    budget = settle(0.01)
    R.limit(
        all(0 <= t[1] <= budget for t in d.lock_time),
        f"and declares inside the ber_settle_syms(0.01, 0) = {budget}-symbol "
        f"budget (worst {max(t[1] for t in d.lock_time)})",
    )
    R.limit(
        all(t[2] > 0.55 for t in d.lock_time),
        "and settles with the eye open (lock_stat > 0.55 at every offset)",
    )

    # --- bn across planned cascades ------------------------------------
    for bn, vals in d.bn_rows:
        if bn >= 0.005:
            R.limit(
                max(vals) - min(vals) < 4.0,
                f"at bn = {bn:g} the three planned cascades agree within "
                f"4 dB ({max(vals) - min(vals):.1f} dB) — `bn` means the "
                f"same thing whatever the planner built",
            )
    spreads = [max(v) - min(v) for _, v in d.bn_rows]
    # Bound the WORST cascade, not the spread between them.
    #
    # A spread bound was the wrong shape and the resamp ctrl fix proved it:
    # `bn = 0.002, sps = 4` improved from -40.4 to -47.5 dB — the cascade
    # whose terminal rate is exactly 1.0, which is the rate that fix
    # repaired — and the spread widened from 5.2 to 6.6 dB as a RESULT. The
    # limit then failed because the object got better, which is a limit
    # that punishes improvement.
    #
    # What a caller actually relies on is that narrowing `bn` never costs
    # them EVM whichever cascade the planner built. That is a claim about
    # the worst row, and it survives any one cascade improving.
    worst = [max(v) for _, v in d.bn_rows]  # EVM in dB: max == worst
    R.limit(
        all(b <= a for a, b in zip(worst, worst[1:])),
        f"and the WORST of the three cascades improves monotonically as "
        f"`bn` narrows ({' -> '.join(f'{w:.1f}' for w in worst)} dB) — "
        f"narrowing the loop never costs a caller EVM, whichever cascade "
        f"the planner built (F4)",
    )
    R.limit(
        spreads == sorted(spreads),
        f"the spread widens monotonically as `bn` narrows "
        f"({' < '.join(f'{s:.1f}' for s in spreads)} dB) — narrowing the "
        f"loop is what separates the cascades, not the planner's choice",
    )
    R.limit(
        all(max(v) < -28.0 for _, v in d.bn_rows),
        "every planned cascade reaches better than -28 dB EVM at every "
        "swept bn, worst case over eight initial offsets",
    )
    R.limit(
        all(len(v) == 3 and all(x < -1.0 for x in v) for _, v in d.bn_rows),
        "and every cell of that sweep is a real measurement, not "
        "`ber_evm_db`'s 0 dB no-lock sentinel",
    )

    # --- the input level ------------------------------------------------
    R.limit(
        any(c[2] == 1 for c in d.clip_rows if c[0] == 64),
        "over-driving a plan that HAS a CIC sets `clipped`",
    )
    R.limit(
        all(c[1] == 0 for c in d.clip_rows),
        "unit amplitude never clips on any plan — the pulse's 1.582x PAPR "
        "is inside the CIC's budgeted headroom",
    )
    R.limit(
        all(c[1] == 0 and c[2] == 0 for c in d.clip_rows if c[0] == 4),
        "a plan with no CIC never sets `clipped`, however hard it is driven",
    )
    under = [r for r in d.amp_rows if r[0] < 0.25]
    R.limit(
        all(r[4] == 0 for r in under),
        "under-drive is NOT reported by any published flag (gh-661): the "
        "worst-driven case still reads clipped = 0",
    )
    # The other half of the same blind spot, and the reason F11 exists: on a
    # CIC-free plan, over-drive costs EVM with the flag still reading clean.
    over8 = [r for r in d.amp_rows if r[0] > 1.0]
    unit8 = next(r for r in d.amp_rows if r[0] == 1.0)
    R.limit(
        all(r[4] == 0 for r in over8),
        "over-drive is NOT reported either on a plan with no CIC — "
        "`clipped` is a CIC quantiser flag, not a level check",
    )
    R.limit(
        all(r[1] > unit8[1] + 5.0 for r in over8),
        f"and it costs real EVM there ({over8[0][1]:.1f} dB at amplitude "
        f"{over8[0][0]:g} against {unit8[1]:.1f} dB at unit) — so the level "
        f"contract is unenforced in BOTH directions",
    )

    # --- m and the rectangle --------------------------------------------
    m2 = next(r for r in d.m_rows if r[0] == 2)
    m4 = next(r for r in d.m_rows if r[0] == 4)
    # The m >= 4 rule is asserted on what it COSTS, not on the lock flag.
    #
    # This used to read `m2[3] < 0.311 <= m4[3]` — m = 2 must not clear the
    # declare threshold. That worked only while the number happened to sit
    # at +0.180, and it stopped being true the moment the resamp ctrl fix
    # improved the rate-1.0 cascades: m = 2 now reads +0.525 and DOES clear
    # the threshold, while still demodulating at -8.7 dB against m = 4's
    # -18.1 dB. So the flag flipped and the guidance did not — the rule is
    # as right as it ever was, and `lock_stat` was never the quantity that
    # discriminates. That is F7, applied: the lock detector answers "is the
    # eye open", not "is this configuration usable".
    R.limit(
        m4[5] < m2[5] - 6.0,
        f"with the rectangle, m = 4 demodulates {m2[5] - m4[5]:.1f} dB "
        f"better than m = 2 ({m4[5]:.1f} vs {m2[5]:.1f} dB) — the m >= 4 "
        f"rule, measured on EVM because `lock_stat` does not separate them "
        f"(m = 2 reads {m2[3]:+.3f} and declares lock at {m2[5]:.1f} dB)",
    )
    R.limit(
        all(r[1] > 0.55 for r in d.m_rows),
        "with the RRC every supported m opens the eye, so the rule is "
        "specific to the rectangle as documented",
    )

    # --- clock tracking --------------------------------------------------
    R.limit(
        all(abs(est - true) < 0.01 for _, true, est in d.ppm_rows),
        f"a sample-clock offset is tracked into `rate` to better than 0.01 "
        f"samples/symbol across +-2000 ppm (worst "
        f"{max(abs(e - t) for _, t, e in d.ppm_rows):.2e})",
    )
    R.limit(
        all(
            (est - 8.0) * (true - 8.0) > 0
            for _, true, est in d.ppm_rows
            if abs(true - 8.0) > 1e-6
        ),
        "and departs from the nominal sps in the right DIRECTION at both "
        "signs — `rate` is a signed estimator, not a magnitude",
    )

    # --- telemetry --------------------------------------------------------
    R.limit(
        len(d.tlm_names) == 6,
        f"the loop publishes exactly six probes ({len(d.tlm_names)})",
    )
    R.limit(
        set(d.tlm_names)
        == {
            "sync.e",
            "sync.ctrl",
            "sync.rate",
            "sync.lock",
            "sync.locked",
            "sync.mu",
        },
        "and they are e / ctrl / rate / lock / locked / mu",
    )


# ═════════════════════════════════════════════════ plots
def plots(d: Data) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig, ax = plt.subplots(figsize=(9, 5))
    # Both detectors on one axis: the shapes are the argument. They share
    # the zeros (so the parity claim covers both) and they do NOT share the
    # slope through them (F15) or the curve's form — DTTL's is visibly not
    # a sinusoid, which is what made `2*pi*peak` the wrong estimator once
    # this report grew a second detector (F14).
    for ted, style in zip(TEDS, ("-", "--")):
        v = d.scurve_by_ted[ted]
        ax.plot(
            v["tau"],
            v["scurve"],
            style,
            lw=1.4,
            label=f"{ted} (slope {v['slope']:.2f})",
        )
    ax.axhline(0, color="0.4", lw=0.8)
    for t0, s in d.zeros:
        ax.axvline(
            t0,
            ls=":",
            lw=1.0,
            color="tab:green" if s < 0 else "tab:red",
            label=("stable (eye centre)" if s < 0 else "unstable (T/2)"),
        )
    ax.set_xlabel("timing offset (symbols)")
    ax.set_ylabel("normalised TED error")
    ax.set_title(
        "Both detectors: same zeros, different slope through them (F14/F15)"
    )
    ax.grid(True, alpha=0.3)
    ax.legend(fontsize=9)
    fig.tight_layout()
    fig.savefig(HERE / "scurve.png", dpi=110)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(9, 5))
    bns = [b for b, _ in d.bn_rows]
    # Both detectors, or the figure shows half of the table above it:
    # solid gardner, dashed dttl, one colour per cascade so the pairing
    # reads as "same plan, two detectors" rather than six unrelated lines.
    for ti, ted in enumerate(TEDS):
        for i, sps in enumerate((4, 8, 64)):
            ax.plot(
                bns,
                [v[i] for _, v in d.bn_rows_by_ted[ted]],
                "o-" if ti == 0 else "s--",
                lw=1.3,
                color=f"C{i}",
                alpha=1.0 if ti == 0 else 0.65,
                label=f"{ted}, sps = {sps}",
            )
    ax.set_xscale("log")
    ax.invert_xaxis()
    ax.set_xlabel("loop noise bandwidth bn (per symbol)")
    ax.set_ylabel("worst-case EVM over 8 offsets (dB)")
    ax.set_title("`bn` means the same thing on every planned cascade")
    ax.grid(True, which="both", alpha=0.3)
    ax.legend(fontsize=9)
    fig.tight_layout()
    fig.savefig(HERE / "bn_sweep.png", dpi=110)
    plt.close(fig)

    fig, (a1, a2) = plt.subplots(1, 2, figsize=(13, 4.5))
    amps = [r[0] for r in d.amp_rows]
    for ted, sty in zip(TEDS, ("o-", "s--")):
        a1.semilogx(
            amps,
            [r[1] for r in d.amp_rows_by_ted[ted]],
            sty,
            lw=1.3,
            label=ted,
        )
    a1.legend(fontsize=8)
    a1.axvline(
        1.0, color="tab:green", ls="--", lw=1.0, label="contracted level"
    )
    a1.set_xlabel("symbol amplitude")
    a1.set_ylabel("EVM (dB)")
    a1.set_title("The level axis is two-sided on BOTH detectors (F6)")
    a1.grid(True, which="both", alpha=0.3)
    a1.legend(fontsize=8)
    a2.semilogx(
        amps, [r[2] for r in d.amp_rows], "o-", lw=1.3, label="lock_stat"
    )
    a2.semilogx(
        amps, [r[4] for r in d.amp_rows], "s--", lw=1.1, label="clipped"
    )
    a2.axhline(0.311, color="0.5", ls=":", lw=1.0, label="declare threshold")
    a2.set_xlabel("symbol amplitude")
    a2.set_title("Over-drive is reported; under-drive is not (gh-661)")
    a2.grid(True, which="both", alpha=0.3)
    a2.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(HERE / "input_level.png", dpi=110)
    plt.close(fig)

    # The session's headline result, and the one number a reader should be
    # able to see rather than reconstruct from a table: `bn` means one
    # bandwidth for gardner at every roll-off and does not for dttl.
    fig, ax = plt.subplots(figsize=(9, 5))
    for ted, sty in zip(TEDS, ("o-", "s--")):
        ax.plot(
            [b for b, _m, _s in d.beta_slope[ted]],
            [abs(v) for _, v, _s in d.beta_slope[ted]],
            sty,
            lw=1.4,
            label=ted,
        )
        # Error bars, because the sd is measured rather than assumed: the
        # scale factor is a mean over seeds and the reader should see how
        # much of its shape is signal.
        ax.errorbar(
            [b for b, _m, _s in d.beta_slope[ted]],
            [abs(v) for _, v, _s in d.beta_slope[ted]],
            yerr=[sd for _, _v, sd in d.beta_slope[ted]],
            fmt="none",
            ecolor="0.4",
            capsize=3,
            lw=1.0,
        )
    ax.axhline(1.0, color="0.4", lw=0.9, ls=":", label="ideal (unity)")
    ax.set_xlabel("RRC roll-off beta")
    ax.set_ylabel("normalised slope at lock")
    ax.set_yscale("log")
    ax.set_title("`bn` names one bandwidth only where this is flat at 1 (F15)")
    ax.grid(True, alpha=0.3, which="both")
    ax.legend(fontsize=9)
    fig.tight_layout()
    fig.savefig(HERE / "beta_slope.png", dpi=110)
    plt.close(fig)

    # Log-log, because the claim IS the slope: two straight lines of
    # gradient 2 and 1, which is easier to check by eye than five ratios.
    fig, ax = plt.subplots(figsize=(9, 5))
    for ted, sty in zip(TEDS, ("o-", "s--")):
        ax.loglog(
            d.amp_law_amps,
            d.amp_law_err[ted],
            sty,
            lw=1.4,
            label=f"{ted} (fitted A^{d.amp_law[ted]:.3f})",
        )
    ax.set_xlabel("symbol amplitude A")
    ax.set_ylabel("|mean detector output| at a fixed offset")
    ax.set_title(
        "Gardner carries A^2, DTTL carries A^1 — the level-error "
        "budget is not shared (F13)"
    )
    ax.grid(True, alpha=0.3, which="both")
    ax.legend(fontsize=9)
    fig.tight_layout()
    fig.savefig(HERE / "amp_law.png", dpi=110)
    plt.close(fig)

    rec = getattr(d, "traj", {})
    if rec:
        fig, axes = plt.subplots(4, 1, figsize=(9, 9), sharex=True)
        for ax, key, lbl in zip(
            axes,
            ("sync.e", "sync.ctrl", "sync.rate", "sync.lock"),
            ("TED error", "control", "tracked sps", "lock_stat"),
        ):
            v = np.asarray(rec.get(key, []))
            ax.plot(v, lw=0.9)
            ax.set_ylabel(lbl)
            ax.grid(True, alpha=0.3)
        axes[-1].set_xlabel("recovered symbol")
        axes[0].set_title("The loop through its own telemetry probes")
        fig.tight_layout()
        fig.savefig(HERE / "trajectory.png", dpi=110)
        plt.close(fig)


def build(write: bool = True) -> Report:
    """Measure, review and assert; emit the report only when asked.

    ``write=False`` is the pytest path: every measurement still runs, so
    every limit is genuinely exercised, but nothing is written into the
    repo. See ``doppler/tests/_validation_common.py``.
    """
    global R
    R = Report(write=write)
    if write:
        DATA.mkdir(parents=True, exist_ok=True)
    section_summary()
    d = characterise()
    review(d)
    limits(d)
    R.executive(
        "RateSync",
        [
            '**`lock_stat` answers "is the eye open", not "is this '
            'configuration usable"** — it does not separate a '
            "correctly-scaled loop from a 32x under-driven one (F7). Judge "
            "a "
            "configuration on EVM, and reserve `locked` for telemetry.",
            "**The caller owns the input level, and the axis is two-sided.** "
            "Over-drive is reported by `clipped` ONLY on a plan containing a "
            "CIC, and there is no under-drive twin on any plan (§2.6, F11) — "
            "so the level contract is unenforced in both directions.",
            "**The T/2 ambiguity resolves itself.** Each parity’s S-curve "
            "carries one stable zero at the eye centre and one unstable at "
            "T/2, on BOTH detectors (§2.2), which is why no eye-sign detector "
            "is needed.",
            "**Gardner carries A^2 and DTTL carries A^1** (§2.6b, F13): the "
            "two detectors do not share a level-error budget, so a gain error "
            "that is benign on one is four times worse on the other.",
            "**DTTL’s low-SNR behaviour is unmeasured here** (F17). Nothing "
            "in this report adds noise, so its lower self-noise near lock is "
            "evidence for the noiseless case only.",
        ],
    )
    if write:
        plots(d)
    R.summary(
        "\n- Raw sweeps: `data/scurve.csv`, `data/bn_sweep.csv`, "
        "`data/beta_slope.csv`, `data/amp_law.csv` — every one of them "
        "carrying both detectors, so any number in the `ted` tables above "
        "can be re-derived rather than taken on the report's word."
    )
    R.emit(HERE / "results.md")
    return R


if __name__ == "__main__":
    sys.exit(cli(build, HERE))
