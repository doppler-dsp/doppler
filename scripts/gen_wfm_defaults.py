#!/usr/bin/env python3
"""Generate the C initialisers for a wfm source and segment, from the manifest.

**One declaration, both directions.** `just-makeit.toml` already declares
every default with `default = ...`, and jm generates Python's from it. C had
no path to that declaration: `native/src/app/wfmgen.c` restated the values as
a struct literal inside `main()`, its own comment saying they *"mirror the
Python Synth/Composer defaults"* — mirrored in three places, shared from
none, with no gate comparing them (doppler#1142).

Two of them were worse than a plain duplicate. `modulation` and `crc` were
restated as enum **indices** (`1`, `1`) while the manifest names them as
**strings** (`"bpsk"`, `"crc16"`), so the literal silently depended on the
ORDER of `[[enum]] bitmod` and `[[enum]] crc`. Append-only protects the tail,
not the head: prepend an entry to either and the manifest still means `bpsk`
while `1` becomes the new second entry — a wrong default with nothing
failing. That is the rot `wfm_names.h` exists to end (doppler#760), one level
up, in a literal no enum gate scans.

This resolves such a default through the field's OWN `enum = "..."` key, never
by searching the enums for a matching string. `"bpsk"` appears in both
`[[enum]] bitmod` (index 1) and `[[enum]] wfm_type` (index 3); a
search-by-value would have picked the wrong one, which is precisely the
mistake a hand-written index invites.

Only fields whose default is NON-ZERO are emitted. A zero default is what a
zero-initialised struct already gives, so writing it would add noise that
says nothing — and the generated macro is meant to be read.

Usage:
    python scripts/gen_wfm_defaults.py --check   # exit 1 if header is stale
    python scripts/gen_wfm_defaults.py --write   # regenerate it
"""

from __future__ import annotations

