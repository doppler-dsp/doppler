RateConverter_state_t *
RateConverter_create (double rate, int compensate)
{
  if (rate <= 0.0)
    return NULL;

  RateConverter_state_t *s = (RateConverter_state_t *)calloc (1, sizeof (*s));
  if (!s)
    return NULL;

  /* NOT the calloc default: RC_PULSE_NONE is 2 so that 0/1 line up with the
     receiver's IANDD/RRC vocabulary. */
  s->pulse      = RC_PULSE_NONE;
  s->rate       = rate;
  s->compensate = compensate;

  rc_plan_entry_t plan[RC_MAX_STAGES];
  int             n = rc_plan (rate, compensate, 0, plan);
  if (n == 0 || !rc_build_stages (s, plan, n))
    {
      free (s);
      return NULL;
    }
  return s;
}

RateConverter_state_t *
RateConverter_create_matched (double rate, int compensate, int pulse,
                              double beta, size_t span, double pulse_sps,
                              size_t num_phases)
{
  /* Written as !(x >= y) so a NaN parameter is rejected, not accepted. */
  if (!(rate > 0.0) || !(beta >= 0.0) || !(beta <= 1.0) || span < 1
      || !(pulse_sps > 0.0) || num_phases < 2u
      || (num_phases & (num_phases - 1u)) != 0u
      || (pulse != RC_PULSE_IANDD && pulse != RC_PULSE_RRC))
    return NULL;

  RateConverter_state_t *s = (RateConverter_state_t *)calloc (1, sizeof (*s));
  if (!s)
    return NULL;

  s->rate       = rate;
  s->compensate = compensate;
  s->pulse      = pulse;
  s->beta       = beta;
  s->span       = span;
  s->pulse_sps  = pulse_sps;
  s->num_phases = num_phases;
  /* The rectangle is exactly one symbol wide, so its matched filter is a
     boxcar of pulse_sps taps — a 2-3 tap sum below four samples per symbol. */
  s->narrow_pulse = (pulse == RC_PULSE_IANDD && pulse_sps < 4.0);

  rc_plan_entry_t plan[RC_MAX_STAGES];
  /* force_terminal: the terminal stage IS the matched filter and the timing
     element, so it exists even when the rate needs no correction. */
  int n = rc_plan (rate, compensate, 1, plan);
  /* The fold replaces the comp FIR — never both. */
  for (int i = 0; i < n; i++)
    plan[i].compensate = 0;
  if (n == 0 || !rc_build_stages (s, plan, n))
    {
      free (s);
      return NULL;
    }
  return s;
}

int
RateConverter_enable_agc (RateConverter_state_t *s, double bn_sym,
                          double alpha)
{
  /* A plain cascade has no pulse, so `bank_e0 / bank_sps` describes nothing
     and there is no reference to derive. Refused rather than guessed. */
  if (s->pulse == RC_PULSE_NONE)
    return DP_ERR_INVALID;
  /* Written as !(x > y) so a NaN is rejected, not accepted. */
  if (!(bn_sym > 0.0) || !(alpha > 0.0) || !(alpha <= 1.0))
    return DP_ERR_INVALID;

  double keep_bn = s->agc_bn_sym, keep_a = s->agc_alpha;
  s->agc_bn_sym = bn_sym;
  s->agc_alpha  = alpha;
  if (!rc_agc_build (s))
    {
      s->agc_bn_sym = keep_bn;
      s->agc_alpha  = keep_a;
      return DP_ERR_INVALID;
    }
  return DP_OK;
}

