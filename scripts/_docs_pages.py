"""One definition of "a docs page" and of "a page exempt from a docs gate".

Three gates (``check_repo_links``, ``check_broker_links``,
``check_clone_notes``) each carried their own copy of both: the walk over
``docs/**/*.md`` and the reader of a ``<glob> <why>`` exempt file. Copies
drift -- one skipped ``archive/`` and the others did not -- so there is one,
here.

* :func:`pages` -- every markdown page a reader can reach. ``docs/c-api``
  (Doxygen's generated output, never hand-written) is never a page; a build
  tree under an example, and a frozen ``archive/``, are not pages either.
* :func:`exempt_globs` -- the globs in an exempt file. The reason after each
  glob is MANDATORY: an exemption nobody can explain is a gap nobody owns.
* :func:`is_exempt` -- whether a repo-relative page matches one of them.
* :func:`prose` -- a page's prose: its text with fenced blocks, code spans
  and generated regions blanked, so a gate that reads WORDS (the retired
  words, the vocabulary) and one that reads code (the symbol names) agree on
  which is which. ``FENCE`` and ``SPAN`` are the two regexes, once.
"""

from __future__ import annotations

import fnmatch
import re
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from pathlib import Path

#: Generated by Doxygen from the headers; there is nothing to edit or gate.
GENERATED = ("docs", "c-api")

#: A fenced code block (``` or ~~~), fence lines included.
FENCE = re.compile(r"^[ \t]*(```|~~~).*?^[ \t]*\1", re.S | re.M)

#: An inline code span on one line.
SPAN = re.compile(r"`([^`\n]+)`")

#: A region a generator owns, between `<!-- name:start -->` and
#: `<!-- name:end -->` (doc-version, corr2d-hypotheses:loss, ...): its words
#: come from the generator's source, which is where they are fixed.
GENERATED_REGION = re.compile(
    r"<!--\s*([\w:.\-]+):start\s*-->.*?<!--\s*\1:end\s*-->", re.S
)


def pages(
    root: Path, tops: tuple[str, ...] = ("docs",), readme: bool = False
) -> list[Path]:
    """Every markdown page under ``tops`` (and ``README.md`` if asked)."""
    out = [root / "README.md"] if readme else []
    for top in tops:
        for p in sorted((root / top).rglob("*.md")):
            parts = p.relative_to(root).parts
            if "build" in parts or "archive" in parts:
                continue
            if parts[: len(GENERATED)] == GENERATED:
                continue
            out.append(p)
    return [p for p in out if p.is_file()]


def exempt_globs(root: Path, rel: str) -> list[str]:
    """Globs from the exempt file ``rel`` (``<glob> <why>`` per line)."""
    f = root / rel
    if not f.exists():
        return []
    out: list[str] = []
    for line in f.read_text(encoding="utf-8").splitlines():
        s = line.strip()
        if not s or s.startswith("#"):
            continue
        glob, _, why = s.partition(" ")
        if not why.strip():
            raise SystemExit(f"{rel}: '{glob}' needs a reason")
        out.append(glob)
    return out


def is_exempt(rel: str, globs: list[str]) -> bool:
    return any(fnmatch.fnmatch(rel, g) for g in globs)


def _blank(m: re.Match[str]) -> str:
    """The match as spaces, newlines kept: a line number and a column in
    the blanked text are the page's."""
    return re.sub(r"[^\n]", " ", m.group(0))


def prose(text: str) -> str:
    """``text`` with generated regions, fenced blocks and code spans blanked.

    What is left is what a reader reads as words. The blanking keeps every
    newline and every column, so a hit's line and column in the result are
    the page's own.
    """
    return SPAN.sub(
        _blank, FENCE.sub(_blank, GENERATED_REGION.sub(_blank, text))
    )
