#!/usr/bin/env python3
"""CarrierNda validation — produces this folder's certification evidence.

Writes ``results.md`` (the authoritative report), the plots it embeds, and
the raw sweeps under ``data/`` so any number in the report can be re-derived
without re-running the measurement.

Three phases, in order:

1. **Characterise** — measure complete behaviour across the input range and
   over time. Tables and plots, no verdicts.
2. **Review** — judge the characterisation: correct-by-design, or a gap.
3. **Limits** — the envelope a caller may rely on, asserted.

Every number is measured from the C through its own binding. Nothing here
models what the C ought to do, and nothing re-implements a measurement the
library already owns: the stimulus is ``doppler.wfm.Synth`` (carrier offset,
pulse shaping and the Es/N0 convention all its), the symbol labels are
``doppler.wfm.PN``, the constellation is ``doppler.mpsk.mpsk_map``, the EMA
coefficient the header derives is checked against
``doppler.detection.det_ema_alpha``, the closed-loop anchor is
``doppler.tests.loop_reference``, and the loop's internal signals come from
its own telemetry probes rather than from anything recomputed here.

**The header is the SSOT and it was read first.** `carrier_nda_core.h` states
the acquisition contract, what the arm window costs, and where the lock
threshold comes from; `test_carrier_nda_core.c` pins what a unit test can pin.
This report measures the LAWS those two state in prose — the ones a point
assertion cannot express — and section 1's claim table says, for every prose
claim in the header, which of the three carries it.

One surface deliberately does NOT appear here: ``carrier_nda_disc()`` is
``JM_FORCEINLINE`` with no binding at all, so every claim about the
discriminator itself is reported **C-ONLY** with the C section that covers it
(see §2.1's note and F10). Measuring the loop and calling it the detector is
exactly the substitution `docs/dev/contributing/validation.md` warns about.

Run:  make validate
"""

