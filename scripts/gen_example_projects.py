#!/usr/bin/env python3
"""Generate the example-project pages: the README, how to get the code, and
every tracked source file of the project.

``example-projects/<name>/`` is a self-contained project a reader builds on
their own. Its docs page used to be the README and nothing else: no
``CMakeLists.txt``, no ``main.c``, no link to the folder, no download. A
reader who installed a package has no checkout, so the trail ended there
(doppler#2856).

So the page is GENERATED from the project, and *is* the code:

1. the README's title,
2. a **Get the code** block: a link to the folder at the release tag and one
   command that fetches just that folder from the release tarball. It sits in
   a ``doc-version`` region, so ``gen_doc_versions.py`` re-stamps it on every
   release and this script writes the same version it would,
3. the README's body, included from between the README's own
   ``<!-- --8<-- [start:body] -->`` and ``[end:body]`` markers (invisible on
   GitHub), so the doc-snippet gates still see each fence as the project's
   own, with the project's Makefile to check its ``make`` goals against,
4. one tab per tracked file of the project, README excepted.

Files are DISCOVERED, never registered:
``git ls-files example-projects/<name>`` is the list. A file added to a
project reaches its page the next time ``make docs-relink`` runs, and
``--check`` (``make docs-check`` and the Docs job) fails until it has: there is
no list to forget to add it to.

Each fence of a language the doc-snippet gates execute (c, python, sh) carries
a ``skip=`` marker with its reason, because the project's own ``Makefile``
builds and runs it; the page is not a second harness.

Usage
-----
    python scripts/gen_example_projects.py --write   # regenerate every page
    python scripts/gen_example_projects.py --check   # exit 1 on any drift
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROJECTS = "example-projects"
PAGES = "docs/example-projects"
REPO_URL = "https://github.com/doppler-dsp/doppler"
BANNER = (
    "<!-- GENERATED by scripts/gen_example_projects.py from the project "
    "folder. Do not edit; run `make docs-relink`. -->"
)

# File name or extension -> fence language. Anything else is plain text.
LANG_BY_NAME = {"CMakeLists.txt": "cmake", "Makefile": "makefile"}
LANG_BY_EXT = {
    ".c": "c",
    ".h": "c",
    ".py": "python",
    ".sh": "sh",
    ".cmake": "cmake",
    ".toml": "toml",
    ".md": "markdown",
}
# The doc-snippet gates execute these fences; the project's own Makefile
# builds and runs the files, so each is marked rather than run twice.
EXECUTED_BY_GATES = {"c", "python", "sh"}
NO_EXEC = (
    "<!-- docs-snippet: no-exec=downloads the release tarball; the clean-"
    "container walk (tests/install) runs it for real -->"
)
SKIP = (
    "<!-- docs-snippet: skip=this is the project's own source, built and "
    "run by its Makefile (make build, make run) -->"
)


def current_version(root: Path = ROOT) -> str:
    """The version a release bumps: pyproject.toml, as gen_doc_versions."""
    text = (root / "pyproject.toml").read_text(encoding="utf-8")
    m = re.search(r'^version\s*=\s*"([^"]+)"', text, re.MULTILINE)
    if not m:
        raise SystemExit("gen_example_projects: no version in pyproject.toml")
    return m[1]


def tracked(root: Path, folder: str) -> list[str]:
    """Tracked files under ``folder``, repo-relative, sorted."""
    r = subprocess.run(
        ["git", "ls-files", "-z", "--", folder],
        cwd=root,
        capture_output=True,
        check=True,
    )
    return sorted(p for p in r.stdout.decode().split("\0") if p)


def projects(root: Path = ROOT) -> list[str]:
    """Every project: a directory under example-projects/ that has tracked
    files. One without a README cannot be rendered, so it is an error naming
    the folder, not a project the docs silently lack."""
    names = {
        p.split("/")[1] for p in tracked(root, PROJECTS) if p.count("/") >= 2
    }
    bare = sorted(
        n for n in names if not (root / PROJECTS / n / "README.md").exists()
    )
    if bare:
        raise SystemExit(
            "example-projects without a README.md (the page's title and body "
            f"come from it): {', '.join(bare)}"
        )
    return sorted(names)


def project_files(root: Path, name: str) -> list[str]:
    """The files that become tabs: every tracked file but the README, with
    the build files first (CMakeLists.txt, Makefile), then the rest."""
    prefix = f"{PROJECTS}/{name}/"
    files = [f for f in tracked(root, prefix) if f != f"{prefix}README.md"]
    first = ["CMakeLists.txt", "Makefile"]
    return sorted(
        files,
        key=lambda f: (
            first.index(f[len(prefix) :]) if f[len(prefix) :] in first else 9,
            f,
        ),
    )


def language(path: str) -> str:
    name = path.rsplit("/", 1)[-1]
    return LANG_BY_NAME.get(name) or LANG_BY_EXT.get(
        "." + name.rsplit(".", 1)[-1] if "." in name else "", "text"
    )


def _fence(text: str) -> str:
    """A backtick fence longer than any run of backticks inside ``text``."""
    longest = max((len(m) for m in re.findall(r"`+", text)), default=0)
    return "`" * max(3, longest + 1)


BODY_MARKS = ("<!-- --8<-- [start:body] -->", "<!-- --8<-- [end:body] -->")


def render_page(root: Path, name: str) -> str:
    """The generated page for one project."""
    base = root / PROJECTS / name
    text = (base / "README.md").read_text(encoding="utf-8")
    title = text.split("\n", 1)[0]
    if not all(m in text for m in BODY_MARKS):
        raise SystemExit(
            f"{PROJECTS}/{name}/README.md: wrap its body (everything after "
            f"the title) in {BODY_MARKS[0]} ... {BODY_MARKS[1]} so the page "
            "can include it"
        )
    v = current_version(root)
    folder = f"{PROJECTS}/{name}"
    out = [
        BANNER,
        "",
        title,
        "",
        "## Get the code",
        "",
        "The files are listed [at the bottom of this page](#the-files). "
        "The tabs there show the project on the development branch; this "
        "fetches the project's folder from the latest release, which can "
        "differ from them until the next release:",
        "",
        "<!-- doc-version:start -->",
        "",
        NO_EXEC,
        "```sh",
        f"curl -fsSL {REPO_URL}/archive/refs/tags/v{v}.tar.gz \\",
        f"  | tar -xz --strip-components=2 doppler-{v}/{folder}",
        "```",
        "",
        f"Or browse [`{folder}/`]({REPO_URL}/tree/v{v}/{folder}).",
        "",
        "<!-- doc-version:end -->",
        "",
        f'--8<-- "{folder}/README.md:body"',
        "",
        "## The files",
        "",
    ]
    for f in project_files(root, name):
        rel = f[len(folder) + 1 :]
        try:
            text = (root / f).read_text(encoding="utf-8")
        except UnicodeDecodeError:
            # A tab cannot show it; the page still names it, and the fetch
            # above brings it.
            out += [
                f'=== "{rel}"',
                "",
                f"    `{rel}` is a binary file ({(root / f).stat().st_size} "
                "bytes): fetch the folder to get it.",
                f"    <!-- {f} -->",
                "",
            ]
            continue
        lang = language(f)
        fence = _fence(text)
        out += [f'=== "{rel}"', ""]
        if lang in EXECUTED_BY_GATES:
            out += [f"    {SKIP}", ""]
        out += [f"    {fence}{lang}", f'    --8<-- "{f}"', f"    {fence}", ""]
    return "\n".join(out).rstrip("\n") + "\n"


def render(root: Path = ROOT) -> dict[str, str]:
    """``{repo-relative page path: text}`` for every project."""
    return {f"{PAGES}/{n}.md": render_page(root, n) for n in projects(root)}


def page_problems(root: Path = ROOT) -> list[str]:
    """Pages and nav entries that no project explains, or that are missing.

    * an orphan: ``docs/example-projects/<x>.md`` (bar the index) with no
      ``example-projects/<x>/`` behind it, which ``--write`` would never
      refresh;
    * a project whose page is not in ``mkdocs.yml``'s nav exactly once: the
      page would build and nobody could reach it.
    """
    names = set(projects(root))
    out = [
        f"{p.relative_to(root).as_posix()}: no example-projects/{p.stem}/ "
        "behind it (delete the page, or restore the project)"
        for p in sorted((root / PAGES).glob("*.md"))
        if p.stem != "index" and p.stem not in names
    ]
    nav = (root / "mkdocs.yml").read_text(encoding="utf-8")
    for n in sorted(names):
        hits = len(
            re.findall(
                rf":\s*example-projects/{re.escape(n)}\.md\s*$", nav, re.M
            )
        )
        if hits != 1:
            out.append(
                f"mkdocs.yml: example-projects/{n}.md is in the nav {hits} "
                "times, want exactly 1"
            )
    return out


def missing_files(root: Path = ROOT) -> list[str]:
    """Every tracked project file whose page does not include it.

    ``render`` writes them all, so this is only non-empty when a page has not
    been regenerated: the reason ``--check`` fails, said per file.
    """
    out = []
    for name in projects(root):
        page = root / PAGES / f"{name}.md"
        text = page.read_text(encoding="utf-8") if page.exists() else ""
        out += [
            f"{PAGES}/{name}.md does not include {f}"
            for f in project_files(root, name)
            if f'--8<-- "{f}"' not in text and f"<!-- {f} -->" not in text
        ]
    return out


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    if "--write" not in argv and "--check" not in argv:
        print(__doc__)
        return 1
    want = render()
    drift: list[str] = []
    for rel, text in sorted(want.items()):
        p = ROOT / rel
        if p.exists() and p.read_text(encoding="utf-8") == text:
            continue
        if "--check" in argv:
            drift.append(rel)
        else:
            p.write_text(text, encoding="utf-8")
    if "--check" in argv:
        if drift:
            print(
                "Example-project pages drift -- run `python scripts/"
                "gen_example_projects.py --write` (make docs-relink):",
                file=sys.stderr,
            )
            for rel in drift:
                print(f"  {rel}", file=sys.stderr)
            for line in missing_files():
                print(f"  {line}", file=sys.stderr)
        problems = page_problems()
        if problems:
            print("Example-project pages:", file=sys.stderr)
            for line in problems:
                print(f"  {line}", file=sys.stderr)
        if drift or problems:
            return 1
        print(f"Example projects: OK -- {len(want)} page(s) up to date")
        return 0
    print(f"Example projects: regenerated {len(want)} page(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
