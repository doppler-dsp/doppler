"""The pending-CI-image-repin gate, exercised over seeded pin blocks.

``scripts/ci-image-repin-check.sh`` takes two pin files as arguments precisely
so this file can drive its decision without a network or a scratch remote —
the same reason ``issue-link-check.sh`` is a script rather than an inline
recipe.

The distinction under test is narrow and is the whole point: **a rebuilt
digest is not a repin.** ``ci-image.yml`` rebuilds nightly and the digest
changes every single time (timestamps, layer ids) while the package set is
identical. A gate that diffed the file would be red every morning, everyone
would learn to ignore it, and the one morning the packages genuinely moved
would look exactly like the others. So the gate compares the two
``CI_IMAGE_FINGERPRINT_*`` values and ``CI_IMAGE_SOURCE_HASH``, and nothing
else — see doppler#1212.
"""

from __future__ import annotations

import re
import subprocess
from typing import TYPE_CHECKING

import pytest
import yaml

from doppler.tests._platform import skip_without_posix_shell
from doppler.tests._repo import repo_root

if TYPE_CHECKING:
    from pathlib import Path

REPO = repo_root(__file__)
SCRIPT = REPO / "scripts" / "ci-image-repin-check.sh"

#: A pin block shaped exactly like the one ``ci-image.yml`` writes.
BLOCK = """\
# GENERATED by .github/workflows/ci-image.yml -- do not hand-edit.
CI_IMAGE_2204=ghcr.io/doppler-dsp/doppler-ci@sha256:{d2204}
CI_IMAGE_2404=ghcr.io/doppler-dsp/doppler-ci@sha256:{d2404}
CI_IMAGE_FINGERPRINT_2204={f2204}
CI_IMAGE_FINGERPRINT_2404={f2404}
CI_IMAGE_SOURCE_HASH={src}
"""

BASE = {
    "d2204": "a" * 64,
    "d2404": "b" * 64,
    "f2204": "c" * 64,
    "f2404": "d" * 64,
    "src": "e" * 64,
}


def _pin(tmp_path: Path, name: str, **over: str) -> Path:
    """Write one pin block, overriding any field."""
    p = tmp_path / name
    p.write_text(BLOCK.format(**{**BASE, **over}))
    return p


def _run(pending: Path, pinned: Path) -> subprocess.CompletedProcess[str]:
    """Run the gate over a (rebuilt, committed) pair of pin blocks."""
    skip_without_posix_shell("the CI-image repin gate")
    return subprocess.run(
        [str(SCRIPT), str(pending), str(pinned)],
        capture_output=True,
        text=True,
        cwd=REPO,
    )


def test_identical_pins_pass(tmp_path: Path) -> None:
    """Nothing moved — the healthy nightly, and the common case."""
    r = _run(_pin(tmp_path, "a"), _pin(tmp_path, "b"))
    assert r.returncode == 0, r.stdout + r.stderr
    assert "OK" in r.stdout


def test_a_rebuilt_digest_alone_is_not_a_repin(tmp_path: Path) -> None:
    """THE case the gate exists to not cry wolf about.

    Both digests differ, both fingerprints and the source hash agree: this is
    every ordinary nightly. A file diff would call this drift.
    """
    pending = _pin(tmp_path, "a", d2204="1" * 64, d2404="2" * 64)
    r = _run(pending, _pin(tmp_path, "b"))
    assert r.returncode == 0, r.stdout + r.stderr


@pytest.mark.parametrize(
    "field",
    ["f2204", "f2404", "src"],
    ids=["fingerprint-2204", "fingerprint-2404", "source-hash"],
)
def test_each_watched_value_fails_when_it_moves(
    tmp_path: Path, field: str
) -> None:
    """Sabotage, one watched value at a time.

    A gate that reads only the first of the three would pass two of these,
    which is the way this class of check rots: it keeps working for the case
    someone tested and silently stops covering the rest.
    """
    pending = _pin(tmp_path, "a", **{field: "9" * 64})
    r = _run(pending, _pin(tmp_path, "b"))
    assert r.returncode == 1, r.stdout + r.stderr
    assert "PENDING" in r.stdout
    assert "gh pr create --head ci/repin-image" in r.stdout


def test_an_unset_value_is_not_agreement(tmp_path: Path) -> None:
    """A pin missing the key must not read as matching.

    ``grep`` finding nothing yields an empty string, and empty-equals-empty is
    how a comparison gate quietly starts passing on a file it cannot parse.
    """
    pinned = tmp_path / "unpinned"
    pinned.write_text("# nothing here\n")
    r = _run(_pin(tmp_path, "a"), pinned)
    assert r.returncode == 1, r.stdout + r.stderr
    assert "<unset>" in r.stdout


def test_the_failure_names_every_moved_value(tmp_path: Path) -> None:
    """Report all of them, not just the first.

    Fixing one and re-running to discover the next is the loop that makes
    people stop reading a gate's output.
    """
    pending = _pin(tmp_path, "a", f2204="9" * 64, f2404="8" * 64)
    r = _run(pending, _pin(tmp_path, "b"))
    assert r.returncode == 1
    assert "CI_IMAGE_FINGERPRINT_2204" in r.stdout
    assert "CI_IMAGE_FINGERPRINT_2404" in r.stdout


def test_the_failure_names_the_merge_cost(tmp_path: Path) -> None:
    """An unlanded repin blocks every merge; the gate says so.

    The weekly run's step summary is this output (doppler#1737), so it is
    where a reader learns why a pending repin is urgent.
    """
    r = _run(_pin(tmp_path, "a", src="9" * 64), _pin(tmp_path, "b"))
    assert r.returncode == 1
    assert "IT BLOCKS EVERY MERGE" in r.stdout


#: The nightly's final step, as ci-image.yml must carry it.
NIGHTLY = REPO / ".github" / "workflows" / "ci-image.yml"
GATE_STEP = "A pending repin ends this run red"


def _nightly_steps(text: str) -> list[dict]:
    yaml = pytest.importorskip("yaml")
    return yaml.safe_load(text)["jobs"]["build"]["steps"]


def _nightly_problems(text: str) -> list[str]:
    """Why ``text`` would NOT end red on a pending repin (empty: it would).

    The decision is the gate's (cases above); this holds the nightly to
    running it: on main, last, unsoftened, against main's pin.
    """
    steps = _nightly_steps(text)
    names = [s.get("name") for s in steps]
    if GATE_STEP not in names:
        return ["no step runs the repin gate"]
    step = steps[names.index(GATE_STEP)]
    run = str(step.get("run", ""))
    out = []
    if names.index(GATE_STEP) != len(steps) - 1:
        out.append("the gate is not the last step")
    if "make -s ci-image-repin-check" not in run:
        out.append("the step does not run make ci-image-repin-check")
    if 'exit "$rc"' not in run:
        out.append("the step does not exit with the gate's status")
    if step.get("continue-on-error"):
        out.append("continue-on-error softens the gate")
    if str(step.get("if", "")) != "github.ref == 'refs/heads/main'":
        out.append("the gate is not limited to main")
    if "checkout -q FETCH_HEAD -- .github/ci-images.env" not in run:
        out.append("the gate compares against the pushed pin, not main's")
    return out


def test_the_nightly_ends_red_on_a_pending_repin() -> None:
    assert _nightly_problems(NIGHTLY.read_text(encoding="utf-8")) == []


@pytest.mark.parametrize(
    ("old", "new", "why"),
    [
        ("make -s ci-image-repin-check", "true", "does not run make"),
        ('exit "$rc"', "exit 0", "does not exit with the gate"),
        (
            "git checkout -q FETCH_HEAD -- .github/ci-images.env\n",
            "",
            "pushed pin, not main's",
        ),
        (
            "      - name: A pending repin ends this run red\n",
            "      - name: A pending repin ends this run red\n"
            "        continue-on-error: true\n",
            "softens the gate",
        ),
    ],
)
def test_a_softened_nightly_is_caught(old: str, new: str, why: str) -> None:
    """Sabotage, on a copy of ci-image.yml: each way to lose the red."""
    text = NIGHTLY.read_text(encoding="utf-8")
    assert old in text, old
    assert any(why in p for p in _nightly_problems(text.replace(old, new, 1)))


#: The refs a push must never rebuild the image on (#1748). Main already
#: holds the pin the merged branch built; rebuilding re-resolves apt against
#: a moved mirror and owes a repin for nothing.
NO_PUSH_REBUILD = ("main",)


def _trigger_problems(text: str) -> list[str]:
    """Why ci-image.yml's push trigger would rebuild on main."""
    doc = yaml.safe_load(text)
    push = (doc.get("on", doc.get(True)) or {}).get("push") or {}
    if "branches" in push:
        # A positive list cannot be audited against "everything but main":
        # `['**']` was the shape that rebuilt on both.
        return ["push names branches, not branches-ignore"]
    ignored = push.get("branches-ignore") or []
    return [
        f"push rebuilds on {ref}"
        for ref in NO_PUSH_REBUILD
        if ref not in ignored
    ]


def test_a_push_to_main_does_not_rebuild() -> None:
    assert _trigger_problems(NIGHTLY.read_text(encoding="utf-8")) == []


@pytest.mark.parametrize(
    ("old", "new", "why"),
    [
        (
            "branches-ignore: [main]",
            "branches: ['**']",
            "names branches",
        ),
        (
            "branches-ignore: [main]",
            "branches-ignore: [develop]",
            "rebuilds on main",
        ),
    ],
)
def test_a_widened_trigger_is_caught(old: str, new: str, why: str) -> None:
    """Sabotage, on a copy of ci-image.yml: each way back to the churn."""
    text = NIGHTLY.read_text(encoding="utf-8")
    assert old in text, old
    assert any(why in p for p in _trigger_problems(text.replace(old, new, 1)))


DOCKERFILE = REPO / "deploy" / "docker" / "Dockerfile.ci"
PIN = REPO / ".github" / "ci-images.env"


def _reproducible_problems(
    dockerfile: str, pin: str, workflow: str
) -> list[str]:
    """Why a rebuild of the CI image could drift off its pin (#1748).

    The two inputs that move upstream -- the base image and the apt mirror
    -- must be build arguments with NO default in Dockerfile.ci (a default
    is a second, stale copy of the pin), their values must be pinned in
    ``.github/ci-images.env``, the workflow must pass them, and only a
    WEEKLY schedule may pick new ones.
    """
    out: list[str] = []
    froms = re.findall(r"^FROM\s+(\S+)", dockerfile, re.M)
    if froms != ["${BASE}"]:
        out.append(f"Dockerfile.ci builds FROM {froms}, not the pinned BASE")
    for arg in ("BASE", "APT_SNAPSHOT", "JB_VERSION", "JB_SHA256"):
        if not re.search(rf"^ARG {arg}$", dockerfile, re.M):
            out.append(f"ARG {arg} is missing or has a default")
    lines = dockerfile.splitlines()
    # Instructions only: the header comment names the snapshot host too.
    code = [
        (i, s) for i, s in enumerate(lines) if not s.lstrip().startswith("#")
    ]
    first_apt = next((i for i, s in code if "apt-get" in s), len(lines))
    rewrite = next(
        (i for i, s in code if "snapshot.ubuntu.com" in s), len(lines)
    )
    if rewrite > first_apt:
        out.append("apt-get runs before the snapshot rewrite")
    # The installer comes from the pinned, checksummed tarball (#1751), never
    # from a live fetch of its logic: get-jb.sh and `jbx install-deps` both
    # resolve the newest install-deps at run time.
    live = [s for _, s in code if "get-jb.sh" in s or "jbx install-deps" in s]
    if live:
        out.append(
            f"Dockerfile.ci fetches its installer live: {live[0].strip()}"
        )
    if not any("sha256sum -c" in s for _, s in code):
        out.append("Dockerfile.ci does not verify the just-bashit tarball")
    vals = dict(
        ln.split("=", 1) for ln in pin.splitlines() if re.match(r"\w+=", ln)
    )
    if not re.fullmatch(r"\d{8}T\d{6}Z", vals.get("CI_APT_SNAPSHOT", "")):
        out.append("pin has no CI_APT_SNAPSHOT timestamp")
    if not re.fullmatch(r"v\d+\.\d+\.\d+", vals.get("CI_JB_VERSION", "")):
        out.append("pin has no CI_JB_VERSION release tag")
    if not re.fullmatch(r"[0-9a-f]{64}", vals.get("CI_JB_SHA256", "")):
        out.append("pin has no CI_JB_SHA256")
    for key in ("2204", "2404"):
        ref = vals.get(f"CI_BASE_{key}", "")
        if not re.fullmatch(r"ubuntu:\d\d\.\d\d@sha256:[0-9a-f]{64}", ref):
            out.append(f"pin has no digest-pinned CI_BASE_{key}")
    for arg in (
        '"BASE=$ref"',
        '"APT_SNAPSHOT=$snap"',
        '"JB_VERSION=$jbv"',
        '"JB_SHA256=$jbsha"',
    ):
        if f"--build-arg {arg}" not in workflow:
            out.append(f"ci-image.yml does not pass {arg}")
    crons = re.findall(r"cron:\s*'([^']+)'", workflow)
    if not crons or any(c.split()[4] == "*" for c in crons):
        out.append(f"re-pin schedule is not weekly: {crons}")
    return out


def _sources() -> tuple[str, str, str]:
    return (
        DOCKERFILE.read_text(encoding="utf-8"),
        PIN.read_text(encoding="utf-8"),
        NIGHTLY.read_text(encoding="utf-8"),
    )


def test_the_image_rebuilds_from_its_pin() -> None:
    assert _reproducible_problems(*_sources()) == []


@pytest.mark.parametrize(
    ("where", "old", "new", "why"),
    [
        (0, "ARG BASE\n", "ARG BASE=ubuntu:24.04\n", "ARG BASE"),
        (0, "ARG APT_SNAPSHOT\n", "ARG APT_SNAPSHOT=x\n", "ARG APT_SNAPSHOT"),
        (0, "FROM ${BASE}\n", "FROM ubuntu:24.04\n", "not the pinned BASE"),
        (
            0,
            "ENV DEBIAN_FRONTEND=noninteractive\n",
            "ENV DEBIAN_FRONTEND=noninteractive\nRUN apt-get update\n",
            "before the snapshot",
        ),
        (1, "CI_APT_SNAPSHOT=", "CI_APT_SNAPSHOT_GONE=", "CI_APT_SNAPSHOT"),
        (
            1,
            "CI_BASE_2204=ubuntu:22.04@",
            "CI_BASE_2204=ubuntu:22.04#",
            "2204",
        ),
        (2, '"APT_SNAPSHOT=$snap"', '"X=$snap"', "does not pass"),
        (0, "ARG JB_VERSION\n", "ARG JB_VERSION=v0.6.0\n", "ARG JB_VERSION"),
        (
            0,
            " | sha256sum -c - \\\n",
            " \\\n",
            "does not verify",
        ),
        (
            0,
            "ARG JB_SHA256\n",
            "ARG JB_SHA256\nRUN bash get-jb.sh\n",
            "fetches its installer live",
        ),
        (1, "CI_JB_SHA256=", "CI_JB_SHA256_GONE=", "CI_JB_SHA256"),
        (2, '"JB_VERSION=$jbv"', '"X=$jbv"', "does not pass"),
        (2, "'17 4 * * 1'", "'17 4 * * *'", "not weekly"),
    ],
)
def test_an_unpinned_input_is_caught(
    where: int, old: str, new: str, why: str
) -> None:
    """Sabotage, on copies: each way back to a drifting rebuild."""
    srcs = list(_sources())
    assert old in srcs[where], old
    srcs[where] = srcs[where].replace(old, new, 1)
    problems = _reproducible_problems(*srcs)
    assert any(why in p for p in problems), problems
