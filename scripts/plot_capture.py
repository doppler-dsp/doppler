#!/usr/bin/env python3
"""Plot any filed telemetry capture. One utility, every subject.

A capture is a self-describing artifact — a 16-byte record stream plus a JSON
sidecar naming every probe (`dp_tlm_capture_core.h`) — which is exactly the
property that makes one plotter enough. Before this there was one script per
subject, and `plot_rx_dynamics.py` was the only one that existed, wired to a
single validator and a single output path.

**This computes nothing.** Every value drawn is a record the object itself
emitted, on the sample index it stamped. That is the rule the prototype states
and the one worth keeping: a plotting script that re-derived the dynamics
would be a second implementation of the thing under test, and the two would
drift. This one cannot disagree with the evidence, because the evidence is its
only input.

It reads FILED captures only — the ones committed under an object's
`data/`, written by `Report.capture` (doppler#846). It never runs a
validator, so the picture and the report cannot come from different runs.

Usage
-----
    python scripts/plot_capture.py <capture.tlm> [-o out.png] [probe ...]
    python scripts/plot_capture.py <capture.tlm> --time [probe ...]
    python scripts/plot_capture.py <capture.tlm> --time --shade stim.on
    python scripts/plot_capture.py <capture.tlm> --list

With no probe names every probe is drawn, one panel per probe, sharing the
sample-index axis. Names may be given with or without the attach prefix, so
`car.freq` and `rx.car.freq` both select the same series. `--time` plots
each record at its stamped sample index over the sidecar's `fs`, so probes
on different clocks -- once a symbol, once a dwell, once a block -- line
up in seconds.

`--shade PROBE` greys every panel wherever that probe reads 0 -- from its
record until the next one, and from its last record to the capture's end.
It is how a capture carries its own context: a harness that cuts the
signal records `stim.on` beside the object's probes (the lock validator's
lifecycle stories do), and the plot shows the cuts from that record, not
from a schedule restated here. It needs `--time`: the shading is placed by
each record's sample stamp, which only the time axis shares across probes.

`--line PROBE=VALUE[:LABEL]` draws a horizontal reference at VALUE on
PROBE's panel: a lock rule's two levels, a detector's fold, a design
baseline. The value is the caller's, read from where it is recorded (a
rules file beside the capture, a design equation); the plotter draws it
and derives nothing. Repeat it for several lines.
`--xlim T0,T1` zooms the shared axis to [T0, T1].

`--names PROBE=V:NAME,...` labels a coded probe's panel with the names of
its values (a lifecycle state, a hand-over source) and draws it as the
steps it is, held from each record to the next. The names are the
caller's, read from the object's own header. `--mark PROBE` draws a
vertical line across every panel at each record where PROBE changes
value, so a symptom on any panel can be placed against, say, the state it
happened in. Both need nothing but the probe's own records.

`--scale PROBE=FACTOR[:UNIT]` draws PROBE times FACTOR and labels its axis
with UNIT: a loop's frequency in cycles per sample times the rate it runs
at reads in Hz. `--mean PROBE=N` draws PROBE's trailing mean of N records
over its raw trace, the raw trace light grey, so a noisy error that fills
its panel solid still shows where it sits; the legend says "mean of N
records". `--vline T[:LABEL]` draws a vertical line across every panel at
x = T, an event the caller read from elsewhere (a validator row's time to
pull in). `--caption TEXT` or `--caption-file PATH` sets one caption
under the figure, generated by the caller from the run's own row and
rules. `--label-size PT` sets the reference lines' label size. Like the
rest, these display the records and compute nothing about the object: the
factor, the events and the caption are all the caller's.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from doppler.tests._validation_common import read_capture  # noqa: E402


def _match(available, wanted):
    """Resolve requested names against the capture's own probe table.

    Suffix matching is deliberate: a capture records probes under the name the
    object was attached with (`rx.car.freq`), while a reader thinks in the
    object's own terms (`car.freq`). Requiring the prefix would make every
    command line depend on a string chosen by whoever wrote the validator.
    """
    if not wanted:
        return list(available)
    out = []
    for w in wanted:
        hits = [n for n in available if n == w or n.endswith("." + w)]
        if not hits:
            raise SystemExit(
                f"no probe matching {w!r}. This capture carries:\n  "
                + "\n  ".join(sorted(available))
            )
        out.extend(hits)
    return out


def _is_symbol(name):
    """Whether a probe carries recovered symbols, drawn as dots.

    A symbol's components end in `.i`/`.q` (`rx.demod.sym.i`). A probe that
    merely sits under a `sym` prefix is loop or decision state and stays a
    line: `rx.sym.lock` is a metric, `rx.sym.locked` a flag.

    >>> [_is_symbol(n) for n in ("rx.demod.sym.i", "rx.sym.lock")]
    [True, False]
    """
    return name.endswith((".i", ".q"))


def _changes(xs, values):
    """The x of each record whose value differs from the one before.

    >>> _changes([0.0, 1.0, 2.0, 3.0], [0, 0, 2, 2])
    [2.0]
    """
    xs, values = list(xs), list(values)
    return [xs[k] for k in range(1, len(xs)) if values[k] != values[k - 1]]


def _off_spans(xs, values, end):
    """The spans `[x0, x1)` over which a step-held probe reads 0.

    Each record holds until the next one; the last holds to `end`.
    Adjacent zero records merge into one span.

    >>> _off_spans([0.0, 1.0, 2.0, 3.0], [0, 1, 0, 0], 5.0)
    [(0.0, 1.0), (2.0, 5.0)]
    >>> _off_spans([0.0, 1.0], [1, 1], 2.0)
    []
    """
    spans = []
    xs, values = list(xs), list(values)
    for k, (x, v) in enumerate(zip(xs, values)):
        if v != 0:
            continue
        x1 = xs[k + 1] if k + 1 < len(xs) else end
        if spans and spans[-1][1] == x:
            spans[-1] = (spans[-1][0], x1)
        else:
            spans.append((x, x1))
    return spans


def _scale_spec(spec):
    """Parse ``PROBE=FACTOR[:UNIT]`` into ``(probe, factor, unit)``.

    The factor is the caller's, read from where the unit is defined (the
    sidecar's rate, a header); the plotter multiplies and labels, and
    derives nothing.

    >>> _scale_spec("car.freq=11e6:Hz")
    ('car.freq', 11000000.0, 'Hz')
    >>> _scale_spec("err.car_unwrapped=1")
    ('err.car_unwrapped', 1.0, '')
    """
    probe, _, rest = spec.partition("=")
    factor, _, unit = rest.partition(":")
    return probe, float(factor), unit


def _running_mean(values, n):
    """The trailing mean of the last ``n`` records at each record.

    A display of the records, drawn over them so a panel the raw trace fills
    solid still shows where it sits; the first ``n - 1`` average what there
    is so far.

    >>> _running_mean([0.0, 2.0, 4.0, 6.0], 2)
    [0.0, 1.0, 3.0, 5.0]
    """
    out, acc = [], 0.0
    vals = list(values)
    for k, v in enumerate(vals):
        acc += v
        if k >= n:
            acc -= vals[k - n]
        out.append(acc / min(k + 1, n))
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("capture", type=Path, help="a filed <name>.tlm")
    ap.add_argument("probes", nargs="*", help="probe names; default all")
    ap.add_argument("-o", "--out", type=Path, help="output PNG")
    ap.add_argument(
        "--list",
        action="store_true",
        help="print the probe table and exit — the capture describes itself",
    )
    ap.add_argument(
        "--time",
        action="store_true",
        help="x is seconds (each record's stamped sample index / the "
        "sidecar's fs), so probes on different clocks line up",
    )
    ap.add_argument(
        "--shade",
        metavar="PROBE",
        help="grey every panel wherever PROBE reads 0 (e.g. stim.on, the "
        "stimulus a harness records); needs --time",
    )
    ap.add_argument(
        "--line",
        action="append",
        default=[],
        metavar="PROBE=VALUE[:LABEL]",
        help="a horizontal reference on PROBE's panel (repeatable)",
    )
    ap.add_argument(
        "--xlim", metavar="T0,T1", help="the shared x range to show"
    )
    ap.add_argument(
        "--names",
        action="append",
        default=[],
        metavar="PROBE=V:NAME,...",
        help="name a coded probe's values on its axis (repeatable)",
    )
    ap.add_argument(
        "--mark",
        metavar="PROBE",
        help="a vertical line across every panel where PROBE changes",
    )
    ap.add_argument(
        "--scale",
        action="append",
        default=[],
        metavar="PROBE=FACTOR[:UNIT]",
        help="draw PROBE times FACTOR, its axis labelled with UNIT "
        "(repeatable); the factor is the caller's",
    )
    ap.add_argument(
        "--mean",
        action="append",
        default=[],
        metavar="PROBE=N",
        help="draw PROBE's trailing mean of N records over its raw trace, "
        "the raw trace lightened (repeatable)",
    )
    ap.add_argument(
        "--vline",
        action="append",
        default=[],
        metavar="T[:LABEL]",
        help="a vertical line across every panel at x = T (repeatable)",
    )
    ap.add_argument(
        "--caption", metavar="TEXT", help="one caption under the figure"
    )
    ap.add_argument(
        "--caption-file",
        type=Path,
        metavar="PATH",
        help="the caption read from a file (the caller generates it)",
    )
    ap.add_argument(
        "--label-size",
        type=float,
        default=9.0,
        metavar="PT",
        help="the font size of --line and --vline labels (default 9)",
    )
    args = ap.parse_args(argv)
    if args.caption and args.caption_file:
        raise SystemExit("--caption and --caption-file: give one")
    caption = args.caption
    if args.caption_file:
        if not args.caption_file.exists():
            raise SystemExit(f"no such caption file: {args.caption_file}")
        caption = args.caption_file.read_text(encoding="utf-8").strip()
    if args.shade and not args.time:
        raise SystemExit(
            "--shade places its spans by sample stamp, which only the time "
            "axis shares across probes: add --time"
        )

    if not args.capture.exists():
        raise SystemExit(f"no such capture: {args.capture}")
    if args.time:
        import json

        meta = Path(str(args.capture) + "-meta").read_text(encoding="utf-8")
        fs = json.loads(meta).get("fs")
        if not fs:
            raise SystemExit(
                f"{args.capture.name} has no fs in its sidecar (captured "
                "with no clock), so it has no time axis: drop --time"
            )
        stamped = read_capture(args.capture, index=True)
        series = {k: v for k, (_, v) in stamped.items()}
        xs = {k: n / float(fs) for k, (n, _) in stamped.items()}
    else:
        series = read_capture(args.capture)
        xs = {k: range(len(v)) for k, v in series.items()}

    if args.list:
        for name in sorted(series):
            print(f"{name:<24} {len(series[name]):>8} records")
        return 0

    names = _match(series, args.probes)
    scales = {}
    for spec in args.scale:
        probe, factor, unit = _scale_spec(spec)
        for hit in _match(names, [probe]):
            scales[hit] = (factor, unit)
            series[hit] = [factor * v for v in series[hit]]
    means = {}
    for spec in args.mean:
        probe, _, n = spec.partition("=")
        if int(n) < 1:
            raise SystemExit(f"--mean {spec}: N is a count of records, >= 1")
        for hit in _match(names, [probe]):
            means[hit] = int(n)
    vlines = []
    for spec in args.vline:
        t, _, label = spec.partition(":")
        vlines.append((float(t), label))
    lines = {}
    for spec in args.line:
        probe, _, rest = spec.partition("=")
        value, _, label = rest.partition(":")
        for hit in _match(names, [probe]):
            lines.setdefault(hit, []).append((float(value), label))
    named = {}
    for spec in args.names:
        probe, _, rest = spec.partition("=")
        ticks = {}
        for item in rest.split(","):
            v, _, label = item.partition(":")
            ticks[float(v)] = label
        for hit in _match(names, [probe]):
            named[hit] = ticks
    marks = []
    if args.mark:
        hits = _match(series, [args.mark])
        if len(hits) != 1:
            raise SystemExit(
                f"--mark names one probe; {args.mark!r} matches "
                + ", ".join(sorted(hits))
            )
        marks = _changes(xs[hits[0]], series[hits[0]])
    spans = []
    if args.shade:
        hits = _match(series, [args.shade])
        if len(hits) != 1:
            raise SystemExit(
                f"--shade names one probe; {args.shade!r} matches "
                + ", ".join(sorted(hits))
            )
        shade = hits[0]
        end = max(
            (float(max(xs[n])) for n in series if len(series[n])),
            default=0.0,
        )
        spans = _off_spans(xs[shade], series[shade], end)
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig, axes = plt.subplots(
        len(names),
        1,
        figsize=(10, 1.9 * len(names)),
        sharex=True,
        squeeze=False,
    )
    for ax, name in zip(axes[:, 0], names):
        # A probe carrying recovered SYMBOLS is a set of discrete decisions,
        # one per symbol period, with nothing in between to interpolate
        # through. A line draws a path the object never took -- on a BPSK
        # stream toggling +-1 it fills the panel solid and shows nothing,
        # where dots show the rails, the acquisition transient and the noise
        # cloud collapsing as the carrier locks. Loop state is the opposite: a
        # continuous quantity sampled per symbol, so it stays a line.
        for x0, x1 in spans:
            ax.axvspan(x0, x1, color="0.85", lw=0, zorder=0)
        for x in marks:
            ax.axvline(x, color="C1", lw=0.7, ls=":", zorder=1)
        for x, label in vlines:
            ax.axvline(x, color="C2", lw=1.0, ls="-.", zorder=1)
            if label and ax is axes[0, 0]:
                ax.annotate(
                    label,
                    (x, 1.0),
                    xycoords=("data", "axes fraction"),
                    xytext=(2, -2),
                    textcoords="offset points",
                    ha="left",
                    va="top",
                    fontsize=args.label_size,
                    color="C2",
                )
        if _is_symbol(name):
            ax.plot(xs[name], series[name], ".", ms=1.5)
        elif name in named:
            ax.plot(xs[name], series[name], lw=0.9, drawstyle="steps-post")
            ax.set_yticks(list(named[name]))
            ax.set_yticklabels(list(named[name].values()), fontsize=7)
        elif name in means:
            ax.plot(xs[name], series[name], lw=0.6, color="0.75", label="raw")
            ax.plot(
                xs[name],
                _running_mean(series[name], means[name]),
                lw=1.1,
                color="C0",
                label=f"mean of {means[name]} records",
            )
            ax.legend(fontsize=args.label_size - 1, loc="upper right")
        else:
            ax.plot(xs[name], series[name], lw=0.9)
        for value, label in lines.get(name, ()):
            ax.axhline(value, color="C3", lw=0.8, ls="--", zorder=1)
            if label:
                ax.annotate(
                    label,
                    (1.0, value),
                    xycoords=("axes fraction", "data"),
                    xytext=(-2, 1),
                    textcoords="offset points",
                    ha="right",
                    va="bottom",
                    fontsize=args.label_size,
                    color="C3",
                )
        unit = scales.get(name, (1.0, ""))[1]
        ax.set_ylabel(
            name.split(".", 1)[-1] + (f" ({unit})" if unit else ""),
            fontsize=8,
        )
        ax.grid(alpha=0.3)
    if args.xlim:
        t0, t1 = (float(v) for v in args.xlim.split(","))
        axes[-1, 0].set_xlim(t0, t1)
    axes[-1, 0].set_xlabel(
        "time (s)" if args.time else "record index (per probe)"
    )
    axes[0, 0].set_title(f"{args.capture.name} — {len(names)} probe(s)")
    fig.tight_layout()
    if caption:
        import textwrap

        text = "\n".join(textwrap.wrap(caption, 150))
        lines_n = text.count("\n") + 1
        # The caption's room in inches, a line of 8 pt text about 0.16 in,
        # so a tall figure does not leave a gap above it.
        height = fig.get_size_inches()[1]
        fig.subplots_adjust(bottom=(0.16 * lines_n + 0.45) / height)
        fig.text(0.01, 0.005, text, fontsize=8, va="bottom", ha="left")

    out = args.out or args.capture.with_suffix(".png")
    fig.savefig(out, dpi=110)
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
