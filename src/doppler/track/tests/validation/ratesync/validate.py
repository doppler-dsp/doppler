HERE = Path(__file__).parent
DATA = HERE / "data"

BETA = 0.35
SPAN = 8
NSYM = 3000
#: Samples per symbol of the GENERATION grid. A fractional timing offset is
#: placed exactly by generating here and decimating by ``FINE // sps``, so an
#: offset of ``j`` fine samples is exactly ``j / FINE`` symbols — no
#: interpolation, and no second implementation of the pulse.
#:
#: Held FIXED rather than as a multiple of `sps`, which is what bounds the
#: cost: the shaping filter is ``2*span*FINE + 1`` taps over ``nsym*FINE``
#: samples, so a grid pinned to ``16*sps`` would run a 16385-tap filter over
#: three million samples at ``sps = 64`` and made this report a seven-minute
#: pytest. 64 samples/symbol is 1/64-symbol timing resolution, finer than any
#: offset this report places.
FINE = 64

#: Independent symbol sequences averaged per roll-off point (§2.2).
_CASC_SEEDS = (7, 1007, 2007, 3007, 4007)

#: Both detectors `ted` selects between. Every axis this report sweeps that
#: the detector can plausibly move — the S-curve (§2.2), the `bn` sweep
#: (§2.5) and the input level (§2.6) — runs over BOTH, because the object
#: has two and a report measuring one of them certifies half the object.
#: It used to measure only Gardner: DTTL's single appearance in the whole
#: document was one row of the claim table pointing at the C test, and the
#: level-axis mechanism was stated as an object-wide law from a
#: Gardner-only sweep. The two detectors do not share an amplitude law
#: (§2.6b), so that was not a safe extrapolation.
TEDS = ("gardner", "dttl")

R = Report()


# ────────────────────────────────────────────────────────── stimulus
def symbols(nsym: int, seed: int = 7) -> np.ndarray:
    """Deterministic +-1 BPSK, from doppler's own PN generator.

    A timing detector only learns from symbol TRANSITIONS, so the sequence
    has to be genuinely random across consecutive symbols; a one-shot LCG of
    the index is strongly periodic and starves the eye statistic. This is
    the same trap `test_ratesync_core.c` documents.

    The bits come from `PN`, a 15-stage maximal-length sequence (period
    32767, comfortably longer than any record here) rather than from numpy.
    That is not ceremony: this report characterises a C object, and a
    stimulus assembled from a different toolchain's primitives is a second
    waveform that has to be kept in agreement with the first by hand.
    """
    rng = np.random.default_rng(seed)
    return np.where(rng.integers(0, 2, nsym) > 0, 1.0, -1.0)


def decim_for(sps: int) -> int:
    """Decimation from the generation grid down to `sps` samples/symbol."""
    return max(1, FINE // int(sps))


def grid_of(sps: int) -> int:
    """Samples per symbol actually generated for this `sps`.

    ``FINE`` when it divides evenly, else the nearest multiple of `sps` at
    or above it, so the decimation stays an integer and the offset stays
    exact.
    """
    return decim_for(sps) * int(sps)


_SHAPED: dict[tuple, np.ndarray] = {}


def shaped_stream(
    sps: int, *, nsym: int = NSYM, amp: float = 1.0, seed: int = 7
) -> tuple[np.ndarray, int]:
    """The fine-grid RRC-shaped BPSK both stimulus helpers decimate.

    Generated by **`Synth`**, the shipped waveform engine, rather than
    reconstructed here. That matters for one specific reason: the pulse has
    to be the SAME waveform the C tests shape with, and building it from
    `rrc_taps` was not, quite. `rrc_taps` returns unit-ENERGY taps whose peak
    falls as the grid is refined (0.1937 at 32 samples/symbol, 0.1370 at 64),
    where the analytic root-raised cosine the C uses has a fixed peak of
    ``1 + beta*(4/pi - 1)`` = 1.09563. This function used to bridge that with
    an explicit ``* sqrt(fine)`` rescale, hand-maintained, and its own
    docstring recorded the stakes: get it wrong and the loop is under-driven
    by ~20 dB and every acquisition claim in this report fails.

    `Synth` needs no bridge. Measured directly, its symbol-centre amplitude
    is 1.0949 at both 8 and 32 samples/symbol -- the analytic pulse, and
    grid-independent -- so there is one waveform and nothing to reconcile.

    Memoised: every offset in a sweep decimates the SAME shaped stream, so
    regenerating it per offset multiplied the report's cost by eight for no
    change in what it measures.
    """
    fine = grid_of(sps)
    key = (fine, nsym, amp, seed)
    if key not in _SHAPED:
        syms = (amp * symbols(nsym, seed)).astype(np.complex64)
        gen = Synth(
            type="symbols",
            symbols=syms,
            pulse="rrc",
            rrc_beta=BETA,
            rrc_span=SPAN,
            sps=fine,
            fs=1.0,
            snr=999.0,
            seed=seed,
        )
        _SHAPED[key] = np.asarray(gen.steps(nsym * fine)).astype(np.complex64)
    return _SHAPED[key], fine


def rrc_bpsk(
    sps: int,
    tau_fine: int,
    *,
    nsym: int = NSYM,
    amp: float = 1.0,
    seed: int = 7,
) -> np.ndarray:
    """RRC-shaped BPSK at an INTEGER `sps`, offset by `tau_fine` fine samples.

    Generated by `Synth` on the fine grid, then decimated starting at
    `tau_fine`. The timing offset is therefore exactly ``tau_fine / grid``
    symbols, and the pulse is the shipped engine's own -- not a numpy
    transcription of the same formula, and not a rescaled tap set.

    Parameters
    ----------
    sps : int
        Samples per symbol of the returned stream.
    tau_fine : int
        Timing offset in fine samples, ``0 <= tau_fine < grid_of(sps)``.
    nsym, amp, seed : optional
        Symbol count, symbol amplitude and PRNG seed.

    Returns
    -------
    ndarray of complex64
    """
    y, _ = shaped_stream(sps, nsym=nsym, amp=amp, seed=seed)
    return np.ascontiguousarray(
        y[tau_fine :: decim_for(sps)].astype(np.complex64)
    )


def tau_symbols(sps: int, tau_fine: int) -> float:
    """The offset `rrc_bpsk` actually realised, in symbols."""
    return tau_fine / float(grid_of(sps))


def eye_at(sps: int, tau_fine: int, ted: str = "gardner") -> float:
    """Mean ``|output symbol|`` at a standing offset — how open the eye is.

    The axis-independent way to tell this validator's two S-curve zeros
    apart. One of them is the eye centre (stable, the equilibrium a closed
    loop settles on) and the other is the T/2 point (unstable); which is
    which used to be decided here by a hard-coded ``slope <= 0`` test, and
    that test is only meaningful relative to a tau axis.

    This validator's tau is a DECIMATION PHASE and the C harness's
    (`dp_tx_cfg_t::tau`) is a TRANSMITTER offset, so the two axes run in
    opposite senses and every slope sign is negated between them. The two
    harnesses consequently agreed on every measured slope and disagreed
    about which zero to call stable — and the sign test cannot break that
    tie, because the sign is what differs.

    Amplitude can. A matched filter's output peaks at the eye centre and
    collapses toward the crossing half a symbol away, and that ordering has
    no sign convention: the zero with the larger mean ``|symbol|`` is the
    eye centre on either axis. Measured here, the two differ by 1.000
    against 0.53-0.79 depending on roll-off, so the discrimination is not
    marginal.

    .. warning::
       **Measurement only — this must never migrate into the object.** It
       works here because a validator generates its own stimulus and so
       knows an open eye exists to be found. ``RateSync`` knows nothing of
       the kind: its input may be noise, an unmodulated dwell, or a buffer
       of zeros, and a timing loop that waited for an open eye before
       trusting itself would stall on exactly those. The object needs no
       such test — it escapes the T/2 point by feedback alone, which is a
       property of the loop's sign rather than of the signal's quality
       (design §6.2).
    """
    x = rrc_bpsk(sps, tau_fine % grid_of(sps), nsym=600)
    _, y, _ = run_sync(x, float(sps), bn=0.0, ted=ted)
    a = np.abs(np.asarray(y))
    return float(a[len(a) // 4 :].mean()) if a.size else 0.0


# ────────────────────────────────────────────────────────── measurement
def settle(bn: float) -> int:
    """Symbols to discard before a steady-state number means anything.

    `ber_settle_syms` is the library's own answer — ``2 * (5/Bn)`` for the
    one running loop. A window pinned to a fraction of the record is the
    documented way a receiver test measures the acquisition transient and
    reports it as steady state.
    """
    return int(ber_settle_syms(bn, 0.0))


def record_syms(bn: float) -> int:
    """Symbols to transmit so a steady-state EVM at `bn` is measurable.

    The settling budget scales as ``1/bn``, so a record length that is fine
    at one bandwidth silently stops being a measurement at another: at
    ``bn = 0.002`` the budget alone is 5000 symbols, and a 3000-symbol
    record leaves NO settled window at all. Deriving the length from the
    budget is what stops a sweep reporting a sentinel as if it were data.
    """
    return max(NSYM, 3 * settle(bn))


def evm_db(y: np.ndarray, bn: float) -> float:
    """Steady-state EVM (dB) of a recovered BPSK stream, via `ber_evm_db`.

    Raises rather than returning a sentinel when the record is too short to
    contain a settled window. `ber_evm_db` answers 0.0 dB for "no lock",
    which in a report table is indistinguishable from a real measurement of
    a scattered constellation — and a sweep that quietly filled a column
    with it is exactly the failure this validator exists to catch.
    """
    lo = settle(bn)
    if y.size < lo + 100:
        raise ValueError(
            f"record of {y.size} symbols has no settled window at bn={bn:g} "
            f"(budget {lo}); use record_syms(bn)"
        )
    # Floored at EVM_FLOOR_DB: below it the error vector is the float
    # floor of a noiseless matched case, not this object's performance.
    return clamp_evm_db(ber_evm_db(y, lo, y.size, 2))


def run_sync(
    x: np.ndarray,
    sps: float,
    *,
    bn: float = 0.01,
    m: int = 2,
    pulse: str = "rrc",
    ted: str = "gardner",
    probes: bool = False,
):
    """Push one stream through a RateSync and return it with its symbols.

    With `probes`, the loop's six telemetry channels are captured — the
    object's own instrumentation, rather than anything recomputed here.

    `ted` selects the detector. It is a real parameter rather than a
    default left implicit, because the caller has two to choose from and
    this report is the evidence for both.
    """
    rs = RateSync(
        sps=sps,
        pulse=pulse,
        beta=BETA,
        span=SPAN,
        m=m,
        num_phases=1024,
        bn=bn,
        zeta=0.707,
        ted=ted,
    )
    tlm = None
    if probes:
        tlm = Telemetry(1 << 20)
        rs.set_telemetry(tlm, "sync")
    y = np.asarray(rs.steps(x))
    rec = tlm.read_dict() if tlm is not None else {}
    return rs, y, rec


@cache
def _eye_centre_fine(sps: int, ted: str) -> int:
    """Fine-sample offset of the EYE CENTRE — the stable equilibrium.

    Scanned by amplitude rather than assumed to be 0, for the reason
    `eye_at` gives: 0 is the T/2 crossing on this validator's axis. The
    scan is coarse because the answer is one of two points half a symbol
    apart, not a continuum, and it is cached because it is a property of
    the cascade's group delay rather than of the roll-off or the seed.
    """
    fine = grid_of(sps)
    offs = range(0, fine, max(1, fine // 8))
    return max(offs, key=lambda o: eye_at(sps, o, ted))


def _cascade_slope(beta: float, ted: str, seed: int = 7) -> float:
    """Normalised S-curve slope at lock, through the real cascade, at @p beta.

    Separate from the §2.2 sweep because the shared stimulus cache is keyed
    on the grid rather than on the pulse: this needs a NEW shaped stream per
    roll-off, and only two offsets of it, so it builds its own rather than
    widening a cache every other section pays for.

    Two offsets, not a full curve: the quantity is a derivative at one
    point, and a paired difference either side of the lock point is the
    whole of it — provided the pair straddles the LOCK point and not the
    other equilibrium. It used to straddle `0`, which on this validator's
    axis is the T/2 crossing, and that is the whole of the retired F15: the
    normaliser was being checked at the zero it was never meant to describe.
    The centre now comes from `_eye_centre_fine`, by amplitude.
    """
    nsym, sps, fine = 3000, 4, FINE
    c = _eye_centre_fine(sps, ted)
    syms = symbols(nsym, seed).astype(np.complex64)
    gen = Synth(
        type="symbols",
        symbols=syms,
        pulse="rrc",
        rrc_beta=beta,
        rrc_span=SPAN,
        sps=fine,
        fs=1.0,
        snr=999.0,
        seed=seed,
    )
    shaped = np.asarray(gen.steps(nsym * fine)).astype(np.complex64)
    dec, j = fine // sps, 2
    got = {}
    for off in ((c - j) % fine, (c + j) % fine):
        x = np.ascontiguousarray(shaped[off::dec])
        rs = RateSync(
            sps=float(sps),
            pulse="rrc",
            beta=beta,
            span=SPAN,
            m=2,
            num_phases=1024,
            bn=0.0,
            zeta=0.707,
            ted=ted,
        )
        tlm = Telemetry(1 << 20)
        rs.set_telemetry(tlm, "s")
        rs.steps(x)
        e = np.asarray(tlm.read_dict().get("s.e", []))
        got[off] = float(e.mean()) if e.size else 0.0
    lo, hi = (c - j) % fine, (c + j) % fine
    return (got[hi] - got[lo]) / (2.0 * j / fine)


def _pct(mv: tuple[float, float]) -> float:
    """Seed-to-seed scatter as a percentage of the mean."""
    return 100.0 * mv[1] / max(abs(mv[0]), 1e-12)


def _cascade_slope_avg(beta: float, ted: str) -> tuple[float, float]:
    """Mean normalised slope over independent symbol sequences, and its sd.

    One realization is a draw, not a constant: a TED's S-curve amplitude
    carries the transition density of the stream driving it, and the
    design assigns that to nobody because it is data (F12). Averaging is
    what makes the scale factor below a measurement with an uncertainty
    rather than a number the next seed contradicts -- measured, Gardner's
    through-cascade agreement at beta 0.1 reads 0.93 on one seed and 0.94
    over several, and the C harness saw the same effect move it by 0.05.
    """
    v = [abs(_cascade_slope(beta, ted, seed=s_)) for s_ in _CASC_SEEDS]
    mean = float(np.mean(v))
    return mean, float(np.std(v, ddof=1)) if len(v) > 1 else 0.0


